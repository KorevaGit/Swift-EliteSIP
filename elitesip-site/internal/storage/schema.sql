-- Схема базы панели EliteSIP.
--
-- Решения, из которых она выведена, — в docs/DECISIONS.md. Здесь только то,
-- что объясняет форму таблиц.
--
-- Времена хранятся строками RFC 3339 в UTC. SQLite своего типа для времени не
-- имеет, а текст сортируется правильно и читается глазами в отладке — это
-- дороже, чем компактность.

PRAGMA foreign_keys = ON;

-- --------------------------------------------------------------------------
-- Настройки самой панели
-- --------------------------------------------------------------------------

-- Немногочисленные значения, которые правятся в панели и уезжают в пакеты
-- активации: сегодня это административный пароль конторы, общий на все машины.
--
-- Ключ-значение, а не столбцы: строк тут будет единицы, а всякая новая
-- потребовала бы миграции ради одного поля.
--
-- Секретов самого сервера здесь нет намеренно — ключ подписи предустановок и
-- секрет отпечатков лежат файлами рядом с базой. Иначе бэкап базы становился бы
-- ещё и связкой ключей.
CREATE TABLE settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- --------------------------------------------------------------------------
-- Администраторы панели
-- --------------------------------------------------------------------------

-- Ролей нет: несколько равных администраторов, все могут всё. Отсюда
-- обязателен audit_log ниже — без него на «кто поменял предустановку» ответа
-- не существует.
CREATE TABLE admins (
    id            INTEGER PRIMARY KEY,
    login         TEXT    NOT NULL UNIQUE,
    password_hash TEXT    NOT NULL,
    created_at    TEXT    NOT NULL,
    -- Не удаляем, а гасим: удалённый администратор унёс бы за собой свои
    -- строки журнала, то есть ровно то, ради чего журнал заведён.
    disabled_at   TEXT
);

CREATE TABLE sessions (
    token_hash TEXT    PRIMARY KEY,
    admin_id   INTEGER NOT NULL REFERENCES admins(id),
    created_at TEXT    NOT NULL,
    expires_at TEXT    NOT NULL
);

CREATE INDEX sessions_by_admin ON sessions(admin_id);

-- --------------------------------------------------------------------------
-- Сотрудники
-- --------------------------------------------------------------------------

-- Единица учёта, и единственная: номер и SIP-пароль — её поля.
--
-- Отдельной сущностью номер был до разбора 24 августа 2026 и стоил двух таблиц
-- с историей назначений. Отменён вместе с увольнением: сотрудник больше не
-- гасится, а удаляется целиком, и переживать номеру нечего. Ответ на «кто
-- сидел на 172 в прошлый вторник» остаётся в журнале — удаление пишет туда имя
-- и номер, и это единственное место, где они переживают карточку.
--
-- Ключ выписывается на человека, машин у человека может быть несколько — см.
-- activations.
--
-- SIP-пароль лежит открытым текстом. Это принятое решение, а не недосмотр:
-- сервер стоит внутри и наружу не открыт. Цена записана в DECISIONS.md и
-- обязывает шифровать выгрузку бэкапа — там же.
CREATE TABLE employees (
    id           INTEGER PRIMARY KEY,
    name         TEXT    NOT NULL,

    -- Пустыми они бывают: человека заводят и до того, как на АТС подняли пир.
    -- Такой сотрудник виден на обзоре незакрытым хвостом, а ключ ему не
    -- выпускается.
    number       TEXT    NOT NULL DEFAULT '',
    sip_password TEXT    NOT NULL DEFAULT '',

    preset_id    INTEGER REFERENCES presets(id),
    created_at   TEXT    NOT NULL
);

-- Двое на одном добавочном — это двое, снимающих звонки друг друга, и заметно
-- это будет не сразу. Правило держит база, а не код.
--
-- Индекс частичный, потому что незаполненных номеров может быть сколько
-- угодно: пустая строка означает «ещё не завели», а не значение.
CREATE UNIQUE INDEX employees_single_number ON employees(number) WHERE number <> '';

-- --------------------------------------------------------------------------
-- Предустановки
-- --------------------------------------------------------------------------

CREATE TABLE presets (
    id          INTEGER PRIMARY KEY,

    -- Имя, под которым предустановка известна снаружи — в пакете активации и в
    -- файле на R2.
    --
    -- Отдельно от name, потому что машина ищет в файле свою предустановку, а
    -- name переименовывают: «Менеджер» станет «Менеджер (первая линия)», и все
    -- машины разом перестанут находить себя. Отдельно от id, потому что
    -- счётчик строк — внутреннее дело базы, и восстановленная из бэкапа база с
    -- другими номерами развела бы машины с их предустановками.
    public_id   TEXT    NOT NULL UNIQUE,

    name        TEXT    NOT NULL UNIQUE,
    created_at  TEXT    NOT NULL,
    archived_at TEXT
);

-- Правка не меняет прошлое, а добавляет ревизию.
--
-- Причина не в аккуратности: ревизия уезжает на все рабочие места и
-- применяется обязательно, без возможности отложить. Значит «откатить на
-- предыдущую» должно быть действием в одно нажатие, а для этого предыдущая
-- должна где-то лежать целиком.
--
-- payload — JSON управляемых полей, ровно тот, что уедет в файл. Хранить
-- разобранным по столбцам значило бы держать вторую копию модели настроек,
-- которая живёт в Swift, и разойтись с ней на первой же новой настройке.
CREATE TABLE preset_revisions (
    id             INTEGER PRIMARY KEY,
    preset_id      INTEGER NOT NULL REFERENCES presets(id),
    revision       INTEGER NOT NULL,
    -- Версия схемы AppSettings, под которую собран payload. Машина со старой
    -- сборкой применит понятное и пропустит остальное — см. DECISIONS.md.
    schema_version INTEGER NOT NULL,
    payload        TEXT    NOT NULL,
    note           TEXT    NOT NULL DEFAULT '',
    author_id      INTEGER REFERENCES admins(id),
    created_at     TEXT    NOT NULL,
    -- Когда ревизия уехала в R2. Пустое означает «ещё не опубликована»: между
    -- сохранением на сайте и появлением файла снаружи проходит выкладка, и в
    -- интерфейсе эта разница должна быть видна честно.
    published_at   TEXT,
    UNIQUE(preset_id, revision)
);

-- --------------------------------------------------------------------------
-- Активации
-- --------------------------------------------------------------------------

-- Активация — это машина. Отдельной сущности «рабочее место» нет: машина
-- существует ровно как активация сотрудника — и исчезает вместе с ним.
--
-- Самого ключа здесь нет и быть не может: он же служит ключом расшифровки
-- пакета на R2, и хранить его рядом с адресом шифротекста значило бы держать
-- замок вместе с ключом. Показать выданный ключ второй раз нельзя — потерялся,
-- выпускается новый.
CREATE TABLE activations (
    id              INTEGER PRIMARY KEY,
    -- Каскад, потому что сотрудник теперь удаляется целиком: активация без
    -- человека — это строка, на которую некому смотреть, а её installation_id
    -- панель после удаления встречает в журнале Worker'а и молча пропускает.
    employee_id     INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    preset_id       INTEGER NOT NULL REFERENCES presets(id),

    key_hash        TEXT    NOT NULL UNIQUE,
    -- Первая группа знаков — чтобы опознать строку в списке, когда
    -- администратор держит ключ в переписке перед глазами.
    key_prefix      TEXT    NOT NULL,

    -- Адрес пакета в R2. Выводится из ключа односторонне, поэтому знание
    -- адреса ничего не даёт: содержимое зашифровано тем же ключом.
    object_key      TEXT    NOT NULL UNIQUE,

    -- Кладётся в пакет и с тех пор сообщается машиной при каждом запросе за
    -- файлом предустановок. Единственное, по чему панель вообще узнаёт машины:
    -- после активации приложение к панели не ходит.
    installation_id TEXT    NOT NULL UNIQUE,

    issued_by       INTEGER REFERENCES admins(id),
    issued_at       TEXT    NOT NULL,
    -- Двое суток от выпуска. Просроченный перевыпускается кнопкой.
    expires_at      TEXT    NOT NULL,

    -- Когда Worker отдал пакет. Заполняется не машиной, а разбором журнала
    -- Worker'а: прямого канала от приложения к панели нет.
    --
    -- Здесь же держится и одноразовость ключа: второй раз Worker пакет не
    -- отдаёт, и «привязка к машине» на деле означает именно это.
    fetched_at      TEXT,

    revoked_at      TEXT,
    note            TEXT    NOT NULL DEFAULT ''
);

CREATE INDEX activations_by_employee ON activations(employee_id);

-- Что панель знает о живых рабочих местах.
--
-- Всё это приходит из отметок, которые Worker оставляет в бакете, раздавая
-- файл предустановок, а не от приложения. Больше узнать нечего, не заводя
-- канал, которого мы сознательно не завели.
--
-- Своей таблицы под «докуда разобрано» нет намеренно: отметки — это состояние,
-- а не череда событий. Забранный пакет виден по пустому fetched_at, а отметка
-- машины перезаписывается целиком, и перечитать её лишний раз ничего не стоит.
CREATE TABLE checkins (
    installation_id TEXT    PRIMARY KEY REFERENCES activations(installation_id) ON DELETE CASCADE,
    last_seen_at    TEXT    NOT NULL,
    app_version     TEXT    NOT NULL DEFAULT '',
    -- Версия схемы AppSettings у машины. По ней видно, кто отстал настолько,
    -- что новые поля предустановки до него не доезжают.
    schema_version  INTEGER,
    preset_revision INTEGER
);

-- --------------------------------------------------------------------------
-- Журнал действий
-- --------------------------------------------------------------------------

CREATE TABLE audit_log (
    id        INTEGER PRIMARY KEY,
    at        TEXT    NOT NULL,
    admin_id  INTEGER REFERENCES admins(id),
    action    TEXT    NOT NULL,
    entity    TEXT    NOT NULL DEFAULT '',
    entity_id INTEGER,
    details   TEXT    NOT NULL DEFAULT ''
);

CREATE INDEX audit_log_by_time ON audit_log(at);

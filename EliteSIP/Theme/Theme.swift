import SwiftUI

/// Единственное место, где заданы размеры, радиусы и цвета.
///
/// Причина, по которой это отдельный слой, а не литералы по месту: приложение
/// живёт на macOS 14–26, и Liquid Glass есть только на 26. Разница должна быть
/// изолирована здесь, чтобы во вьюхах не было ни одного `#available`.
enum Theme {

    /// Вертикальные промежутки между ярусами панели.
    ///
    /// Заданы поимённо, а не общим шагом: расстояния здесь неравные по смыслу.
    /// Поле набора и ряд управления — соседи одного действия, поэтому между ними
    /// почти ничего; управление и макросы — разные классы, и разделяет их только
    /// воздух, без линии.
    enum Gap {
        /// Полоса заголовка → строка состояния.
        ///
        /// Меньше остальных: капсула профиля относится к заголовку — тот же
        /// вопрос «что это за окно», только с ответом «и под каким номером».
        /// Воздуха ровно столько, чтобы точки светофора её не касались.
        static let titleToStatus: CGFloat = 4
        /// Строка состояния → поле ввода.
        static let statusToHeader: CGFloat = 5
        /// Поле ввода → ряд управления.
        static let headerToControls: CGFloat = 5
        /// Ряд управления → макросы.
        static let controlsToMacros: CGFloat = 15
        /// Макросы → кнопка завершения.
        static let macrosToAction: CGFloat = 15
    }

    enum Metrics {
        /// Панель узкая и фиксированной ширины — это софтфон, а не окно почты.
        ///
        /// Габариты сознательно поджаты: окно висит поверх CRM весь рабочий
        /// день, и каждая лишняя точка ширины отъедает место у того, с чем
        /// оператор реально работает. Дайлпада, ради которого держались 280,
        /// больше нет; 270 — компромисс: подписи макросов в три колонки
        /// перестают ужиматься до нечитаемого, а окно всё равно уже прежнего.
        static let panelWidth: CGFloat = 270

        /// Высота, с которой окно панели создаётся.
        ///
        /// Компактного вида больше нет: без макросов панель и так компактна, а
        /// два размера требовали переключателя, который занимал место ради
        /// состояния, в которое почти не переходят.
        ///
        /// Настоящую высоту панель считает сама из числа макросов и того,
        /// свёрнута ли она, и ставит окну через `PanelHeight`. Здесь нужно
        /// какое-то значение до первого прохода раскладки — иначе окно
        /// мигнёт размером содержимого `NSHostingController`.
        static let panelInitialHeight: CGFloat = 250

        /// Строка состояния: капсула профиля, слот беды, шестерёнка.
        ///
        /// Ушла из полосы заголовка вниз, под неё. Раньше она делила линию со
        /// светофором ради экономии 28 точек, и это стоило двух вещей: у окна
        /// не было имени, а номер стоял так близко к кнопкам окна, что читался
        /// как четвёртая из них. Теперь заголовок отвечает на «что это за
        /// окно», строка под ним — на «под каким номером я работаю».
        static let statusBarHeight: CGFloat = 22

        // Высоты полосы заголовка здесь намеренно нет. Её рисует окно, и она
        // системная: на macOS 26 замер живого окна дал 32 точки, а не 28, как
        // на прежних версиях. Своё число тут означало бы, что панель считает
        // высоту неправильно ровно на разницу, — поэтому вёрстка отвечает за
        // содержимое, а рамку ей считает `window.frameRect(forContentRect:)`.

        /// Сторона квадрата подсветки под курсором у кнопок строки состояния.
        static let statusIconHitSize: CGFloat = 22

        /// Высота капсулы профиля. Совпадает со строкой: капсула и есть строка,
        /// остальное в ней — подписи рядом.
        static let profilePickerHeight: CGFloat = 22

        /// Сколько места в строке состояния капсула отобрать не может.
        ///
        /// Ширина капсулы плавает: у профиля есть пометка, и она разной длины.
        /// Слот беды при этом обязан оставаться читаемым — «Нет сети» и
        /// «Профиль без пароля» важнее пометки, которую оператор и так знает,
        /// раз сидит за этой машиной.
        static let troubleSlotMinWidth: CGFloat = 72

        /// Точка состояния в капсуле.
        ///
        /// 8, а не прежние 6: точка осталась единственным, чем показано обычное
        /// состояние — «На линии» рядом с зелёным кружком занимало место и не
        /// сообщало ничего сверх него.
        static let statusDotDiameter: CGFloat = 8

        /// Высота шапки — одна на все состояния панели.
        ///
        ///
        /// Поле набора в покое и карточка собеседника в разговоре занимают
        /// ровно столько же: иначе при ответе на вызов шапка вырастала бы и
        /// сдвигала вниз всё, что под ней. При двух линиях этот же слот делится
        /// на два поля по 22 точки.
        static let headerHeight: CGFloat = 52

        /// Неподвижная нижняя зона: кнопка звонка и история.
        static let actionHeight: CGFloat = 46
        /// Ширина «Истории». Задана явно, чтобы кнопка звонка занимала всё
        /// оставшееся место и не меняла ширину от длины подписи.
        static let historyWidth: CGFloat = 64

        /// Ряд управления: удержание, микрофон, перевод. Ниже клавиш макросов и
        /// с подписью в строку, а не столбиком, — так ряд читается как другой
        /// класс элементов, а не как первый ряд сетки.
        static let controlHeight: CGFloat = 32

        /// Ниже этого клавиша макроса не сжимается. Верхнего предела нет: сетка
        /// забирает всю свободную вертикаль, иначе между ней и кнопкой
        /// завершения оставался бы провал, который нечем занять.
        static let macroMinHeight: CGFloat = 58
        /// Три в ряд: подпись макроса задаёт оператор, предсказать её ширину
        /// нельзя, но три коротких кнопки в 250 точек влезают всегда.
        static let macroColumns = 3

        /// Ширина окна входящего. Высота не задаётся — окно подгоняется под
        /// содержимое.
        ///
        /// Фиксированная высота здесь уже стоила бага: в макете два состояния,
        /// 186 и 244 точки, но зафиксировать их значит получить пустую полосу
        /// между именем звонящего и кнопками всякий раз, когда содержимого
        /// меньше расчётного — например когда сервер не прислал имя.
        static let incomingCallPanelWidth: CGFloat = 320

        // Шкала отступов: 2 / 4 / 6 / 8 / 12. Пять ступеней на всё, и всё, что
        // отступает, отступает одной из них.
        //
        // Две мелкие добавлены 5 августа 2026, когда выяснилось, что в вёрстке
        // живут одиннадцать разных значений — 1, 2, 3, 4, 5, 6, 8, 10, 12, 14.
        // Половина из них отличалась друг от друга на точку, то есть не
        // отличалась вовсе: разницу между 3 и 4 глаз не видит, а вот
        // необходимость каждый раз выбирать между ними — вполне.
        //
        // Вертикальные промежутки между ярусами панели сюда не входят: они
        // неравные по смыслу и живут поимённо в `Theme.Gap` (принцип 6).
        static let hairSpacing: CGFloat = 2
        static let tightSpacing: CGFloat = 4
        static let contentPadding: CGFloat = 12
        static let sectionSpacing: CGFloat = 8
        static let elementSpacing: CGFloat = 6

        /// Высота поля одной линии, когда линий две. Слот шапки делится на два
        /// таких поля, поэтому число связано с `headerHeight`, а не со шкалой.
        static let lineFieldHeight: CGFloat = 22
        /// Кегль номера в поле набора. Живёт здесь, а не в `Text`, потому что
        /// нужен и SwiftUI, и AppKit: поле набора собрано на `NSTextField`.
        static let dialedNumberSize: CGFloat = 18
        /// Точка активной линии в этом поле.
        static let lineDotDiameter: CGFloat = 6
        /// Поле номера перевода и кнопки под ним. Габариты, а не отступы:
        /// шкала про воздух между элементами, а не про их размер.
        static let transferFieldHeight: CGFloat = 34
        static let transferButtonHeight: CGFloat = 30

        /// Непрозрачность выключенного элемента.
        ///
        /// 0.57, а не прежние 0.35, и это решение по строке «выключенный ряд
        /// управления» из этапа 1. Три почти невидимые кнопки читались как
        /// сломанные, а не как «пока нечем пользоваться»; на прозрачной
        /// поверхности они пропали совсем — фон под ними сам по себе неровный,
        /// и бледная подпись растворялась в чужом тексте.
        ///
        /// Число одно на обе темы: разное означало бы, что выключенность в
        /// одной из них читается иначе, а это одно и то же состояние.
        static let disabledOpacity: Double = 0.57
    }

    /// Размеры иконок: три, и только три.
    ///
    /// Было четыре — 10, 11, 12, 13, — и соседние отличались на точку, то есть
    /// не отличались. Три ступени различимы: мелкая при подписи, средняя в
    /// кнопках строки состояния, крупная в неподвижном низу, где иконка
    /// работает вместо подписи.
    enum Icon {
        static let small: CGFloat = 10
        static let medium: CGFloat = 12
        static let large: CGFloat = 14
    }

    enum Radius {
        /// Радиусы после редизайна: 12 и 8 вместо прежних 16 и 10.
        ///
        /// Панель стала уже и ниже, и прежние скругления на клавише в 54 точки
        /// читались как капсула. Значения те же, что в макете.
        ///
        /// Их ровно два, и третьего числа здесь не будет. Была ещё
        /// необъявленная «шестёрка» в трёх местах — подсветка иконок строки
        /// состояния и поле линии; разница в две точки глазом не читается, и
        /// она сведена к `control`. Капсула профиля скругляется по половине
        /// своей высоты (`capsule`), а не третьим числом: у капсулы радиус —
        /// не решение, а следствие высоты.
        static let surface: CGFloat = 12
        static let control: CGFloat = 8

        /// Радиус капсулы: половина высоты того, что скругляем.
        static func capsule(height: CGFloat) -> CGFloat { height / 2 }
    }

    /// Начертания из макета.
    ///
    /// Заданы размером, а не именованным стилем (`.caption`, `.body`): окно
    /// входящего фиксированной ширины и висит поверх чужого интерфейса, а
    /// Dynamic Type на крупной настройке растянул бы его в половину экрана.
    /// Для остальных экранов по-прежнему используются системные стили.
    enum Text {
        /// Подпись «Входящий вызов».
        static let incomingCaption = Font.system(size: 11)
        /// Номер звонящего.
        static let incomingNumber = Font.system(size: 24, weight: .medium, design: .rounded)
        /// Имя звонящего и указание под ним.
        static let incomingDetail = Font.system(size: 13)
        /// Цифра, которую надо нажать, — в тексте указания.
        static let incomingTarget = Font.system(size: 15)
        /// Цифра на кнопке-цели и на клавише набора.
        static let controlKey = Font.system(size: 20, design: .rounded)
        /// Надпись на кнопке.
        static let controlLabel = Font.system(size: 13, weight: .medium)
        /// Состояние регистрации в бейдже панели.
        static let panelStatus = Font.system(size: 13)
        /// Вторая строка бейджа — срок регистрации или время повтора.
        static let panelDetail = Font.system(size: 10)

        /// Номер в поле набора: пока номер набирают, он и есть главное.
        ///
        /// Кегль вынесен в `Metrics.dialedNumberSize`, потому что само поле
        /// собрано на `NSTextField` и просит `NSFont`, а не `Font`.
        static let dialedNumber = Font.system(
            size: Theme.Metrics.dialedNumberSize, weight: .light, design: .rounded
        )
        /// Имя собеседника в разговоре — крупно. Оператор работает с человеком,
        /// а не с цифрами: имя читается, номер только сверяется.
        static let callerName = Font.system(size: 17, weight: .medium)
        /// Номер собеседника под именем — мелко и вторым планом.
        static let callerNumber = Font.system(size: 11, design: .rounded)
        /// Длительность разговора.
        static let callTimer = Font.system(size: 11, weight: .medium, design: .rounded)
        /// Название окна в полосе заголовка.
        ///
        /// Системная величина заголовка окна: полосу рисует окно, а надпись —
        /// мы, и кегль обязан совпасть с тем, что было бы у системного.
        static let windowTitle = Font.system(size: 13, weight: .semibold)
        /// Номер, под которым зарегистрирован менеджер.
        static let statusNumber = Font.system(size: 11, weight: .semibold)
        /// Мелкий текст строки состояния и подписей управления.
        ///
        /// 11, а не 10: на 10 пунктах состояние клиента в светлой теме
        /// переставало читаться совсем — светло-серое по светлому.
        static let statusDetail = Font.system(size: 11)
        /// Собеседник в поле линии, когда линий две.
        static let lineTitle = Font.system(size: 12, weight: .medium)
        /// Подпись под иконкой в неподвижном низу — «История». Мельче всех
        /// прочих: рядом с иконкой она уточнение, а не подпись кнопки.
        static let actionCaption = Font.system(size: 10)
        /// Подпись макроса — крупно, это главная цель для мыши в разговоре.
        static let macro = Font.system(size: 15, weight: .medium)
    }

    enum Palette {
        static let answer = Color.green
        static let decline = Color.red
        static let registered = Color.green
        static let connecting = Color.orange
        static let offline = Color.secondary
        static let failure = Color.red

        /// Три уровня текста, заданные цветом, а не прозрачностью.
        ///
        /// Прозрачность здесь перестала работать вместе с прозрачным фоном
        /// панели: полупрозрачный текст поверх полупрозрачной поверхности
        /// перемножается, и предсказать итог на произвольном фоне нельзя — а
        /// под панелью бывает и белая CRM, и тёмный терминал. Системные
        /// `.secondary` и `.tertiary` не годятся по той же причине, плюс
        /// иерархический `.tertiary` появился только в macOS 12.
        ///
        /// Числа подобраны замером по пикселям живого окна, в худшем случае —
        /// панель поверх тёмного фона, где она садится на серый 176 и тёмному
        /// тексту тяжелее всего. Против него: основной 9.7:1, второй 4.65:1
        /// (норма AA — 4.5), третий 3.0:1.
        ///
        /// В светлой теме основной текст чёрный, и это решение о контрасте:
        /// запас нужен не ради нормы, а потому что фон под панелью произволен.
        /// В тёмной менять было нечего — белый на тёмном таким свойством не
        /// обладает, и уровни там по-прежнему белый с прозрачностью.
        static func textPrimary(_ scheme: ColorScheme) -> Color {
            scheme == .dark ? Color.white.opacity(0.92) : Color.black
        }

        /// Второй уровень стоит ровно на норме. Ниже нельзя: этим цветом
        /// набраны таймер и номер собеседника, а их читают.
        static func textSecondary(_ scheme: ColorScheme) -> Color {
            scheme == .dark
                ? Color.white.opacity(0.70)
                : Color(red: 0.24, green: 0.26, blue: 0.30)
        }

        /// Третий — разделители, шеврон и подписи, которые читают редко.
        static func textTertiary(_ scheme: ColorScheme) -> Color {
            scheme == .dark
                ? Color.white.opacity(0.50)
                : Color(red: 0.34, green: 0.37, blue: 0.42)
        }
    }
}

/// Поверхность окна панели: размытие того, что за окном, плюс подкраска.
private struct PanelSurface: ViewModifier {

    let cornerRadius: CGFloat

    @Environment(\.colorScheme) private var scheme

    /// Сила подкраски поверх размытия. 0 — только размытие, 1 — глухой фон.
    ///
    /// 0.30 — потому что укрывать содержимое соседнего окна должно размытие, а
    /// не подкраска. Подкраска гасит всё разом, вместе с цветом; размытие
    /// убирает буквы и оставляет тон. Нужен второй эффект: панель должна
    /// подхватывать цвет того, что под ней, а не показывать чужой текст.
    ///
    /// Путь до числа стоит помнить, чтобы не пройти его снова: 0.57 с
    /// прототипа (там панель лежала внутри своего окна, настоящего
    /// просвечивания не было вовсе) → 0.70 на `.clear` — сквозь панель
    /// читались чужие буквы → 0.80 на `.regular` — глухой чёрный прямоугольник,
    /// потому что плотность задавали оба разом.
    ///
    /// Число одно на обе темы и обе ступени: оно решает одну задачу — вернуть
    /// поверхности собственную светлоту поверх чужой.
    private static let tint: Double = 0.30

    // Отдельного множителя для тёмной темы больше нет. Он был — 0.76, из
    // соображения «тёмный материал и сам по себе тёмный», — и замер его
    // опроверг: над светлой CRM тёмная панель уходила в средне-серый, и белый
    // текст давал на ней 3.2:1 при норме 4.5. Беда несимметрична по темам:
    // светлой панели тёмный фон снизу не мешает, а тёмной светлый мешает,
    // потому что текст на ней светлее фона, а не темнее. Одно число на обе
    // темы держит обе читаемыми, а просвечивание остаётся: тон панели
    // по-прежнему меняется вслед за тем, что под ней.

    func body(content: Content) -> some View {
        content.compatBackground {
            base.compatOverlay {
                RoundedRectangle(cornerRadius: cornerRadius)
                    .fill(scheme == .dark
                          ? Color.black.opacity(Self.tint)
                          : Color.white.opacity(Self.tint))
            }
        }
    }

    @ViewBuilder
    private var base: some View {
        if #available(macOS 26.0, *) {
            // `.regular` — ради размытия, а не ради плотности.
            //
            // Разница между ним и `.clear` не в том, «сколько видно», а в том,
            // **что** видно. `.clear` рассчитан на стекло поверх картинки: он
            // почти не размывает, и сквозь панель читались буквы соседнего
            // окна — глаз путал чужой текст со своим. `.regular` размывает, и
            // сквозь него проходит только тон: панель подхватывает цвет того,
            // что под ней, оставаясь при этом своей поверхностью.
            //
            // Первый заход с `.regular` провалился не из-за него: подкраска
            // тогда осталась от `.clear` — 0.80, — и вместе они дали глухой
            // чёрный прямоугольник. Здесь подкраска втрое слабее, потому что
            // работу по укрытию содержимого делает размытие.
            Color.clear.glassEffect(.regular, in: .rect(cornerRadius: cornerRadius))
        } else {
            CompatMaterial(
                material: .hudWindow,
                blending: .behindWindow,
                cornerRadius: cornerRadius
            )
        }
    }
}

/// Наложение поверх содержимого, а не замена фона: под ним может быть и
/// материал, и сплошная заливка, и подсветка должна работать одинаково.
private struct HoverHighlight: ViewModifier {

    let cornerRadius: CGFloat
    let isEnabled: Bool

    @State private var isHovered = false

    func body(content: Content) -> some View {
        content
            .compatOverlay {
                RoundedRectangle(cornerRadius: cornerRadius)
                    .fill(Color.primary.opacity(isHovered && isEnabled ? 0.12 : 0))
                    // Наложение обязано быть прозрачным для мыши, иначе оно же
                    // и съест нажатие, ради которого рисовалось.
                    .allowsHitTesting(false)
            }
            .onHover { isHovered = $0 }
            .compatAnimation(.easeOut(duration: 0.12), value: isHovered)
    }
}

extension View {

    /// Основная поверхность: стекло на macOS 26, материал ниже.
    ///
    /// Три ступени, а не две: `Material` из SwiftUI появился только в macOS 12,
    /// поэтому на Catalina и Big Sur тот же системный эффект берётся напрямую у
    /// AppKit. Плоской заливки нет ни на одной ступени.
    @ViewBuilder
    func themedSurface(cornerRadius: CGFloat = Theme.Radius.surface) -> some View {
        if #available(macOS 26.0, *) {
            self.glassEffect(.regular, in: .rect(cornerRadius: cornerRadius))
        } else if #available(macOS 12.0, *) {
            self.background(.ultraThinMaterial, in: RoundedRectangle(cornerRadius: cornerRadius))
        } else {
            self.background(
                CompatMaterial(material: .hudWindow, cornerRadius: cornerRadius)
            )
        }
    }

    /// Фон окна панели: то, что за окном, размытое и подкрашенное.
    ///
    /// Три ступени, как и у `themedSurface`, но с одним общим требованием —
    /// размывать надо **то, что за окном**, а не содержимое своего же. Прежний
    /// `.withinWindow` этого не умеет в принципе, и никакая прозрачность с ним
    /// не работает: под материалом оказывался непрозрачный фон самого окна.
    /// Вместе с этим окно обязано быть непрозрачным «нет» — см. `showPhoneWindow`.
    ///
    /// Подкраска задаёт поверхности собственную светлоту. Без неё материал
    /// поверх пёстрой CRM даёт мутно-серый, одинаково грязный в обеих темах, и
    /// мелкий текст по такому фону не спасают ни кегль, ни цвет. Величина
    /// подобрана на живом окне поверх настоящей CRM и закреплена числом.
    func themedPanelSurface(cornerRadius: CGFloat = Theme.Radius.surface) -> some View {
        modifier(PanelSurface(cornerRadius: cornerRadius))
    }

    /// Подсветка при наведении курсора.
    ///
    /// Нужна всем кнопкам со стилем `.plain`: он рисует только содержимое и
    /// никакой реакции на курсор не даёт. Для окна входящего это не косметика —
    /// оператор должен видеть, что попал в цель, до того как нажмёт, иначе
    /// промах по цифре выглядит как неработающая кнопка.
    ///
    /// Цвет берётся от `.primary`: в тёмной теме это белый и подсвечивает, в
    /// светлой — чёрный и притемняет. То есть верно в обеих.
    func hoverHighlight(
        cornerRadius: CGFloat = Theme.Radius.control,
        isEnabled: Bool = true
    ) -> some View {
        modifier(HoverHighlight(cornerRadius: cornerRadius, isEnabled: isEnabled))
    }

    /// Поверхность управляющего элемента — слабый слой поверх фона панели.
    ///
    /// Несимметрична по темам намеренно: на тёмном фоне светлая плашка заметна
    /// при 0.09, на светлом тёмная — только начиная с 0.06. Симметричное
    /// значение в одной из тем всегда сливалось с панелью.
    func themedControlSurface(cornerRadius: CGFloat = Theme.Radius.control) -> some View {
        modifier(ControlSurface(cornerRadius: cornerRadius))
    }
}

private struct ControlSurface: ViewModifier {

    let cornerRadius: CGFloat

    @Environment(\.colorScheme) private var scheme

    func body(content: Content) -> some View {
        content.compatBackground {
            RoundedRectangle(cornerRadius: cornerRadius)
                .fill(scheme == .dark
                      ? Color.white.opacity(0.09)
                      : Color.black.opacity(0.06))
        }
    }
}

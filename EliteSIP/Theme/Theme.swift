/// Поверхность окна панели: то, что за окном, размытое системой.
///
/// Своей подкраски поверх материала больше нет — снята 6 августа 2026 вместе
/// с уходом на системные цвета текста. Она была плёнкой в 0.30 белого или
/// чёрного и возвращала поверхности собственную светлоту поверх чужой; путь до
/// числа шёл через 0.57, 0.70 на `.clear` и 0.80 на `.regular`, и каждый шаг
/// был замером.
///
/// Отменена не потому, что была неправа, а потому что решала снятую задачу.
/// Стабильная светлота нужна была нашим цветам текста: их приходилось
/// подбирать под известный фон. Системные подбираются сами, и плёнка осталась
/// бы платой без покупки — панель от неё только глуше и дальше от материала,
/// который macOS рисует под остальными окнами.
///
/// Что при этом ушло: тон панели теперь целиком чужой. Размытие снимает буквы,
/// но не цвет, и над красной CRM панель будет розоватой. Это принято.
private struct PanelSurface: ViewModifier {

    let cornerRadius: CGFloat

    func body(content: Content) -> some View {
        content.compatBackground { base }
    }

    @ViewBuilder
    private var base: some View {
        // Две ветки: есть стекло — стекло, нет стекла — непрозрачно.
        //
        // «Без стекла» значит «без прозрачности», а не «другой полупрозрачный
        // материал»: замер живого окна показал, что матовый `hudWindow`
        // человек читает тем же стеклом — сквозь него так же видно чужое окно.
        //
        // Веток было три, и средняя — материал для систем ниже macOS 26 —
        // держалась на догадке: там он-де и есть системный вид. Живая проверка
        // на Big Sur 18 августа 2026 догадку опровергла: экран вызова оказался
        // слишком прозрачным и попросту нечитаемым поверх чужих окон. Причём
        // проверить это раньше было негде — на машине разработки ручной тумблер
        // включён, то есть все замеры «без стекла» шли по непрозрачной ветке.
        //
        // Теперь правило одно и не зависит от настройки: нет стекла в системе —
        // нет и прозрачности. Ручной тумблер при этом остаётся тем же, чем был,
        // — единственным способом получить непрозрачность там, где стекло есть.
        if !Theme.Chrome.usesLiquidGlass {
            RoundedRectangle(cornerRadius: cornerRadius)
                .fill(Color(NSColor.windowBackgroundColor))
        } else if #available(macOS 26.0, *) {
            // `.regular` — ради размытия, а не ради плотности.
            //
            // Разница между ним и `.clear` не в том, «сколько видно», а в том,
            // **что** видно. `.clear` рассчитан на стекло поверх картинки: он
            // почти не размывает, и сквозь панель читались буквы соседнего
            // окна — глаз путал чужой текст со своим. `.regular` размывает, и
            // сквозь него проходит только тон: панель подхватывает цвет того,
            // что под ней, оставаясь при этом своей поверхностью.
            //
            // Первый заход с `.regular` провалился не из-за него: поверх него
            // тогда осталась подкраска от `.clear` — 0.80, — и вместе они дали
            // глухой чёрный прямоугольник. Подкраски больше нет вовсе, и
            // укрытие чужого содержимого целиком на размытии.
            Color.clear.glassEffect(.regular, in: .rect(cornerRadius: cornerRadius))
        } else {
            // Недостижимо: `usesLiquidGlass` истинно только с macOS 26. Ветка
            // существует ради полноты `if`, и красит она тем же, чем первая, —
            // не материалом, чтобы недостижимость не обернулась прозрачным
            // окном, если условие однажды разъедется.
            RoundedRectangle(cornerRadius: cornerRadius)
                .fill(Color(NSColor.windowBackgroundColor))
        }
    }
}

/// Поверхность окна входящего: стекло панели плюс подкраска.
///
/// Отдельно от `PanelSurface` по двум причинам сразу. Первая — сама подкраска
/// (`Theme.Metrics.incomingSurfaceTint`). Вторая — «Уменьшение прозрачности»:
/// когда системная настройка включена, стекла нет вовсе, и плёнка в 0.30
/// поверх пустоты оставила бы окно почти без фона. Значит у поверхности обязан
/// быть непрозрачный вариант, а не только плёнка поверх материала.
///
/// Панели такой вариант не нужен: у неё есть рамка окна и полоса заголовка,
/// которые система рисует сама. Окно входящего borderless — без фона от него
/// остаётся текст, висящий над чужим интерфейсом.
private struct IncomingSurface: ViewModifier {

    let cornerRadius: CGFloat

    @Environment(\.colorScheme) private var scheme

    /// `@State` с `onReceive`, а не `@StateObject`: тот появился в macOS 11, а
    /// срез x86_64 обязан работать на Catalina.
    @State private var reducesTransparency = NSWorkspace.shared.accessibilityDisplayShouldReduceTransparency

    func body(content: Content) -> some View {
        content
            .compatBackground { base }
            .onReceive(
                NSWorkspace.shared.notificationCenter.publisher(
                    for: NSWorkspace.accessibilityDisplayOptionsDidChangeNotification
                )
            ) { _ in
                reducesTransparency = NSWorkspace.shared.accessibilityDisplayShouldReduceTransparency
            }
    }

    @ViewBuilder
    private var base: some View {
        // Три повода к непрозрачности, и все просят одного и того же:
        // системное «уменьшение прозрачности», наш ручной тумблер и система без
        // стекла. Последний добавлен 18 августа 2026 вместе с той же правкой у
        // панели: окно входящего borderless, и полупрозрачное оно висит над
        // чужим интерфейсом ещё хуже, чем панель, — у него нет ни рамки, ни
        // полосы заголовка, только текст.
        if reducesTransparency || !Theme.Chrome.usesLiquidGlass {
            RoundedRectangle(cornerRadius: cornerRadius)
                .fill(Color(NSColor.windowBackgroundColor))
        } else {
            material.compatOverlay {
                RoundedRectangle(cornerRadius: cornerRadius)
                    .fill(
                        (scheme == .dark ? Color.black : Color.white)
                            .opacity(Theme.Metrics.incomingSurfaceTint)
                    )
            }
        }
    }

    @ViewBuilder
    private var material: some View {
        if Theme.Chrome.usesLiquidGlass, #available(macOS 26.0, *) {
            Color.clear.glassEffect(.regular, in: .rect(cornerRadius: cornerRadius))
        } else {
            // Сюда доходит только система со стеклом, у которой стекло почему-то
            // не собралось. Непрозрачная заливка вместо материала — по тому же
            // доводу, что и у панели: пустой фон у borderless-окна хуже, чем
            // плоский.
            RoundedRectangle(cornerRadius: cornerRadius)
                .fill(Color(NSColor.windowBackgroundColor))
        }
    }
}

/// Наложение поверх содержимого, а не замена фона: под ним может быть и
/// материал, и сплошная заливка, и подсветка должна работать одинаково.
private struct HoverHighlight: ViewModifier {

    let cornerRadius: CGFloat
    let isEnabled: Bool

    @State private var isHovered = false

    func body(content: Content) -> some View {
        content
            .compatOverlay {
                RoundedRectangle(cornerRadius: cornerRadius)
                    .fill(Color.primary.opacity(isHovered && isEnabled ? 0.12 : 0))
                    // Наложение обязано быть прозрачным для мыши, иначе оно же
                    // и съест нажатие, ради которого рисовалось.
                    .allowsHitTesting(false)
            }
            .onHover { isHovered = $0 }
            .compatAnimation(.easeOut(duration: 0.12), value: isHovered)
    }
}

extension View {

    /// Основная поверхность: стекло на macOS 26, плоская заливка везде ниже.
    ///
    /// Ступеней было три — стекло, `ultraThinMaterial` с macOS 12 и `hudWindow`
    /// на Catalina, — и держались они на том, что полупрозрачная поверхность
    /// внутри окна выглядит системно. Правка 18 августа 2026 сняла прозрачность
    /// у самого окна на системах без стекла, а поверхность внутри непрозрачного
    /// окна размывает уже не чужой интерфейс, а собственный фон: тот же серый,
    /// только мутный. Плоская заливка честнее и читается лучше.
    @ViewBuilder
    func themedSurface(cornerRadius: CGFloat = Theme.Radius.surface) -> some View {
        if !Theme.Chrome.usesLiquidGlass {
            self.background(
                RoundedRectangle(cornerRadius: cornerRadius)
                    .fill(Color(NSColor.controlBackgroundColor))
            )
        } else if #available(macOS 26.0, *) {
            self.glassEffect(.regular, in: .rect(cornerRadius: cornerRadius))
        } else {
            self.background(
                RoundedRectangle(cornerRadius: cornerRadius)
                    .fill(Color(NSColor.controlBackgroundColor))
            )
        }
    }

    /// Фон окна панели: то, что за окном, размытое и подкрашенное.
    ///
    /// Три ступени, как и у `themedSurface`, но с одним общим требованием —
    /// размывать надо **то, что за окном**, а не содержимое своего же. Прежний
    /// `.withinWindow` этого не умеет в принципе, и никакая прозрачность с ним
    /// не работает: под материалом оказывался непрозрачный фон самого окна.
    /// Вместе с этим окно обязано быть непрозрачным «нет» — см. `showPhoneWindow`.
    ///
    /// Подкраска задаёт поверхности собственную светлоту. Без неё материал
    /// поверх пёстрой CRM даёт мутно-серый, одинаково грязный в обеих темах, и
    /// мелкий текст по такому фону не спасают ни кегль, ни цвет. Величина
    /// подобрана на живом окне поверх настоящей CRM и закреплена числом.
    func themedPanelSurface(cornerRadius: CGFloat = Theme.Radius.surface) -> some View {
        modifier(PanelSurface(cornerRadius: cornerRadius))
    }

    /// Фон окна входящего: то же стекло, что у панели, плюс своя подкраска.
    ///
    /// Отдельный рецепт, а не `themedPanelSurface`, — см.
    /// `Theme.Metrics.incomingSurfaceTint`.
    func themedIncomingSurface(cornerRadius: CGFloat = Theme.Radius.surface) -> some View {
        modifier(IncomingSurface(cornerRadius: cornerRadius))
    }

    /// Подсветка при наведении курсора.
    ///
    /// Нужна всем кнопкам со стилем `.plain`: он рисует только содержимое и
    /// никакой реакции на курсор не даёт. Для окна входящего это не косметика —
    /// оператор должен видеть, что попал в цель, до того как нажмёт, иначе
    /// промах по цифре выглядит как неработающая кнопка.
    ///
    /// Цвет берётся от `.primary`: в тёмной теме это белый и подсвечивает, в
    /// светлой — чёрный и притемняет. То есть верно в обеих.
    func hoverHighlight(
        cornerRadius: CGFloat = Theme.Radius.control,
        isEnabled: Bool = true
    ) -> some View {
        modifier(HoverHighlight(cornerRadius: cornerRadius, isEnabled: isEnabled))
    }

    // `themedSidebarSurface` убрана: материал сайдбара рисует система.
    //
    // Своя плавающая панель повторяла руками то, что `NSSplitViewItem.sidebar`
    // даёт с 10.11, — подложку, полную высоту под полосой заголовка и стекло на
    // macOS 26. Оставить её значило бы положить второй материал поверх
    // системного и получить муть там, где обещано стекло.

    /// Поверхность управляющего элемента — слабый слой поверх фона панели.
    ///
    /// Несимметрична по темам намеренно: на тёмном фоне светлая плашка заметна
    /// при 0.09, на светлом тёмная — только начиная с 0.06. Симметричное
    /// значение в одной из тем всегда сливалось с панелью.
    func themedControlSurface(cornerRadius: CGFloat = Theme.Radius.control) -> some View {
        modifier(ControlSurface(cornerRadius: cornerRadius))
    }
}

private struct ControlSurface: ViewModifier {

    let cornerRadius: CGFloat

    @Environment(\.colorScheme) private var scheme

    func body(content: Content) -> some View {

import AppKit
import SwiftUI

/// Единственное место, где заданы размеры, радиусы и цвета.
///
/// Причина, по которой это отдельный слой, а не литералы по месту: приложение
/// живёт на macOS 14–26, и Liquid Glass есть только на 26. Разница должна быть
/// изолирована здесь, чтобы во вьюхах не было ни одного `#available`.
enum Theme {

    /// Вертикальные промежутки между ярусами панели.
    ///
    /// Заданы поимённо, а не общим шагом: расстояния здесь неравные по смыслу.
    /// Поле набора и ряд управления — соседи одного действия, поэтому между ними
    /// почти ничего; управление и макросы — разные классы, и разделяет их только
    /// воздух, без линии.
    enum Gap {
        /// Полоса заголовка → строка состояния.
        ///
        /// Меньше остальных: капсула профиля относится к заголовку — тот же
        /// вопрос «что это за окно», только с ответом «и под каким номером».
        /// Воздуха ровно столько, чтобы точки светофора её не касались.
        static let titleToStatus: CGFloat = 4
        /// Строка состояния → поле ввода.
        static let statusToHeader: CGFloat = 5
        /// Поле ввода → ряд управления.
        static let headerToControls: CGFloat = 5
        /// Ряд управления → макросы.
        static let controlsToMacros: CGFloat = 15
        /// Макросы → кнопка завершения.
        static let macrosToAction: CGFloat = 15

        // Ярусы окна входящего. Тоже поимённо и тоже неравные: шапка и карточка
        // отвечают на «что это за вызов» и стоят близко, а кнопки от них
        // отделены, потому что это уже действие.

        /// Шапка с якорем → карточка вызова.
        static let incomingHeaderToCaller: CGFloat = 8
        /// Карточка вызова → кнопки.
        static let incomingCallerToActions: CGFloat = 14
    }

    enum Metrics {
        /// Панель узкая и фиксированной ширины — это софтфон, а не окно почты.
        ///
        /// Габариты сознательно поджаты: окно висит поверх CRM весь рабочий
        /// день, и каждая лишняя точка ширины отъедает место у того, с чем
        /// оператор реально работает. Дайлпада, ради которого держались 280,
        /// больше нет; 270 — компромисс: подписи макросов в три колонки
        /// перестают ужиматься до нечитаемого, а окно всё равно уже прежнего.
        static let panelWidth: CGFloat = 270

        /// Высота, с которой окно панели создаётся.
        ///
        /// Компактного вида больше нет: без макросов панель и так компактна, а
        /// два размера требовали переключателя, который занимал место ради
        /// состояния, в которое почти не переходят.
        ///
        /// Настоящую высоту панель считает сама из числа макросов и того,
        /// свёрнута ли она, и ставит окну через `PanelHeight`. Здесь нужно
        /// какое-то значение до первого прохода раскладки — иначе окно
        /// мигнёт размером содержимого `NSHostingController`.
        static let panelInitialHeight: CGFloat = 250

        /// Строка состояния: капсула профиля, слот беды, шестерёнка.
        ///
        /// Ушла из полосы заголовка вниз, под неё. Раньше она делила линию со
        /// светофором ради экономии 28 точек, и это стоило двух вещей: у окна
        /// не было имени, а номер стоял так близко к кнопкам окна, что читался
        /// как четвёртая из них. Теперь заголовок отвечает на «что это за
        /// окно», строка под ним — на «под каким номером я работаю».
        static let statusBarHeight: CGFloat = 22

        // Высоты полосы заголовка здесь намеренно нет. Её рисует окно, и она
        // системная: на macOS 26 замер живого окна дал 32 точки, а не 28, как
        // на прежних версиях. Своё число тут означало бы, что панель считает
        // высоту неправильно ровно на разницу, — поэтому вёрстка отвечает за
        // содержимое, а рамку ей считает `window.frameRect(forContentRect:)`.

        /// Сторона квадрата подсветки под курсором у кнопок строки состояния.
        static let statusIconHitSize: CGFloat = 22

        /// Высота капсулы профиля. Совпадает со строкой: капсула и есть строка,
        /// остальное в ней — подписи рядом.
        static let profilePickerHeight: CGFloat = 22

        /// Сколько места в строке состояния капсула отобрать не может.
        ///
        /// Ширина капсулы плавает: у профиля есть пометка, и она разной длины.
        /// Слот беды при этом обязан оставаться читаемым — «Нет сети» и
        /// «Профиль без пароля» важнее пометки, которую оператор и так знает,
        /// раз сидит за этой машиной.
        static let troubleSlotMinWidth: CGFloat = 72

        /// Точка состояния в капсуле.
        ///
        /// 8, а не прежние 6: точка осталась единственным, чем показано обычное
        /// состояние — «На линии» рядом с зелёным кружком занимало место и не
        /// сообщало ничего сверх него.
        static let statusDotDiameter: CGFloat = 8

        /// Высота шапки — одна на все состояния панели.
        ///
        ///
        /// Поле набора в покое и карточка собеседника в разговоре занимают
        /// ровно столько же: иначе при ответе на вызов шапка вырастала бы и
        /// сдвигала вниз всё, что под ней. При двух линиях этот же слот делится
        /// на два поля по 22 точки.
        static let headerHeight: CGFloat = 52

        /// Неподвижная нижняя зона: кнопка звонка и история.
        static let actionHeight: CGFloat = 46
        /// Ширина «Истории». Задана явно, чтобы кнопка звонка занимала всё
        /// оставшееся место и не меняла ширину от длины подписи.
        static let historyWidth: CGFloat = 64

        /// Ряд управления: удержание, микрофон, перевод. Ниже клавиш макросов и
        /// с подписью в строку, а не столбиком, — так ряд читается как другой
        /// класс элементов, а не как первый ряд сетки.
        static let controlHeight: CGFloat = 32

        /// Ниже этого клавиша макроса не сжимается. Верхнего предела нет: сетка
        /// забирает всю свободную вертикаль, иначе между ней и кнопкой
        /// завершения оставался бы провал, который нечем занять.
        static let macroMinHeight: CGFloat = 58
        /// Три в ряд: подпись макроса задаёт оператор, предсказать её ширину
        /// нельзя, но три коротких кнопки в 250 точек влезают всегда.
        static let macroColumns = 3

        /// Ширина окна настроек менеджера. Высота не задаётся: её считает
        /// содержимое, и окно подстраивается.
        ///
        /// 420. Первый заход был на 560 из плана, и живое окно его опровергло:
        /// вместе с содержимым оно просило 882 точки высоты и не влезало даже
        /// на большой монитор — а окно настроек обязано быть видно целиком.
        ///
        /// Ужато не одной шириной: вместе с ней уменьшены управляющие элементы
        /// (`controlSize(.small)`), кегли и отступы. Одна ширина ничего бы не
        /// дала — высоту набирают строки, а не поля.
        static let settingsWidth: CGFloat = 420

        /// Колонка подписей в настройках.
        ///
        /// Одна на все строки: иначе контролы соседних строк не стоят в колонку,
        /// и глаз ищет их заново на каждой.
        ///
        /// 72 — по самой длинной подписи («Громкость», «Площадка», «Микрофон»)
        /// кеглем `.callout`, и ни точкой больше. Первый заход был на 108 «с
        /// запасом», и запас вышел боком: после сжатия окна до 420 колонке
        /// контролов осталось 274 точки, и в них перестали помещаться ни
        /// «Автоматическая регулировка усиления», ни три кнопки рингтона.
        static let settingsLabelColumn: CGFloat = 72

        /// Поправка на разницу отрисовки системных контролов в настройках.
        ///
        /// Переключатель рисует пилюлю с полем внутри своего кадра, а кнопка —
        /// рамку вплотную к нему. Из-за этого правый край кнопки, прижатой к
        /// той же вертикали, что и переключатели, оказывается дальше: замер по
        /// пикселям живого окна дал 399.5 против 393.5.
        ///
        /// Число одно и применяется в одном месте — к кнопке «Управление»,
        /// единственной прижатой вправо. Остальные кнопки стоят слева, и их
        /// правый край ни с чем не выравнивается.
        static let settingsButtonEdgeInset: CGFloat = 6

        // Окно «Управление». Второе окно, которое тянут мышью, и единственное с
        // боковым списком разделов. Числа здесь — не свободный выбор: сайдбар
        // фиксирован, а содержимое подстраивается под остаток, и обе контрольные
        // ширины замеряются на живом окне.

        /// Ширина бокового списка разделов. Фиксированная: список не тянется
        /// вместе с окном, иначе на широком мониторе девять коротких названий
        /// разъезжаются по полосе в треть экрана.
        ///
        /// 188 — по самому длинному названию («Обслуживание») кеглем `.callout`
        /// вместе со значком, отступами плашки выделения и точкой
        /// несохранённого справа.
        static let adminSidebarWidth: CGFloat = 188

        /// Колонка подписей в «Управлении». Шире менеджерских 72, потому что
        /// подписи здесь длиннее по существу: «Отображаемое имя», «Время
        /// регистрации», «Добавочный комнаты». Ужимать их до 72 значило бы
        /// переносить каждую вторую в две строки.
        static let adminLabelColumn: CGFloat = 132

        /// Потолок ширины у строк «подпись — управление».
        ///
        /// Без него растяжимое окно даёт ползунок разброса длиной во весь
        /// монитор, и окно читается как сломанное, а не как просторное.
        /// Растягиваются только настоящие списки — профили, макросы, очереди,
        /// шаги стука.
        static let adminContentMaxWidth: CGFloat = 560

        /// Порог перестроения списков в два столбца, по ширине контентной
        /// области. Один порог, а не плавная резина: у растяжимого окна иначе
        /// исчезает сам метод проверки — «правильных» чисел становится
        /// бесконечно много, и замерить нечего.
        static let adminTwoColumnThreshold: CGFloat = 700

        /// Первая контрольная ширина: сайдбар плюс строка во всю свою ширину
        /// плюс поля. Уже этого подписи начинают переноситься.
        static let adminMinWidth: CGFloat = 780
        /// Ниже этого раздел «Входящие» перестаёт помещаться целиком, и самый
        /// плотный экран окна уходит под прокрутку.
        static let adminMinHeight: CGFloat = 560

        /// Вторая контрольная ширина: та, на которой списки встают в два
        /// столбца. Она же — размер окна при первом открытии.
        static let adminIdealWidth: CGFloat = 980
        static let adminIdealHeight: CGFloat = 640

        /// Плашка выделенного раздела в сайдбаре.
        ///
        /// Выделение рисуется заливкой, а не акцентным стилем кнопки: на
        /// Catalina акцентного стиля нет вовсе, и прежний бар разделов
        /// обозначал выбранное галочкой вместо значка. С плашкой галочка не
        /// нужна — значок остаётся значком.
        static let adminSidebarRowHeight: CGFloat = 28
        static let adminSidebarRadius: CGFloat = 7

        /// Скругление самой панели сайдбара. Крупнее, чем у строк внутри: так
        /// панель читается как отдельный слой, а не как рамка вокруг списка.
        static let adminSidebarPanelRadius: CGFloat = 10

        /// Точка «здесь есть несохранённое» у пункта сайдбара.
        static let adminDirtyDotDiameter: CGFloat = 6

        /// Окно живой трассы SIP. Уже этого строка `INVITE sip:...` начинает
        /// переноситься, а перенесённая трасса не читается вовсе.
        static let traceMinWidth: CGFloat = 640
        static let traceMinHeight: CGFloat = 320

        // Окно истории. Единственное окно приложения, которое тянут мышью:
        // строк в нём столько, сколько было звонков, и предугадать удобную
        // высоту за оператора нельзя. Поэтому здесь не размер, а нижняя граница.

        /// Уже этого строка истории перестаёт быть строкой.
        ///
        /// Ширину задаёт не строка, а верхний ряд: четыре кнопки фильтров со
        /// значками-подсказками, календарь и снимок. Строка звонка в 520 точек
        /// укладывалась, а ряд — нет: на 520 подпись «Пропущенные» ужималась до
        /// «Пропущенн…», и живое окно это показало сразу. Ужимать подписи
        /// нельзя, значит окно не может быть уже своего управления.
        static let historyMinWidth: CGFloat = 600
        /// Ниже этого список перестаёт быть списком: видно две строки, и окно
        /// отвечает на «кому я звонил» одним звонком.
        static let historyMinHeight: CGFloat = 380

        /// Правая колонка строки истории: длительность или исход сверху, время
        /// с датой снизу.
        ///
        /// Задана числом, а не содержимым, ради одного: кнопки повторного
        /// набора всех строк обязаны стоять на одной вертикали. Иначе они ездят
        /// по горизонтали от длины исхода и попасть в нужную с первого раза
        /// нельзя.
        ///
        /// 124 — по самому длинному, что здесь стоит: «15:57 06.08.2026».
        /// Слова исхода короче и в эту ширину помещаются все шесть; причины
        /// отказа здесь больше нет вовсе — в окне её не пишут.
        static let historyOutcomeColumn: CGFloat = 124

        /// Значок исхода — в строке истории и якорем в шапке окна входящего.
        ///
        /// Крупный: в истории он единственный, что различает четыре состояния
        /// звонка, и читается первым. Стрелка внутри — половина диаметра.
        ///
        /// Имя без «history» с 7 августа 2026: значок перестал быть частью
        /// одного окна — тем же рисует себя якорь в шапке входящего. Размер там
        /// свой и иконочный: в истории значок главный в строке, а в шапке он
        /// стоит рядом с подписью в 11 точек и на двадцати двух возвышался над
        /// ней. Это метрика строки истории, а не самой фигуры.
        static let outcomeBadgeSize: CGFloat = 22

        /// Значок-подсказка на кнопке фильтра истории.
        ///
        /// Вдвое меньше значка строки (22), и это уже вторая правка размера:
        /// на 14 стрелка спорила с подписью за внимание, хотя на кнопке
        /// главное — слово. Значок здесь только напоминает, как эта же вещь
        /// выглядит в списке, и напоминать ему положено вполголоса.
        static let historyFilterGlyph: CGFloat = 11

        /// Кнопка повторного набора в строке истории — квадрат.
        ///
        /// Квадрат, а не набивка вокруг значка: разная набивка по горизонтали и
        /// по вертикали давала приплюснутый прямоугольник, формы которого в
        /// приложении больше нигде нет. 28 — по клавише строки состояния
        /// (`statusIconHitSize` 22) плюс воздух под рамку с фоном.
        static let historyRedialButton: CGFloat = 28

        /// Клетка дня в календаре истории.
        ///
        /// Квадрат: месяц раскладывается сеткой семь на шесть, и неквадратная
        /// клетка делает её то шире, то выше в зависимости от месяца.
        static let historyDayCell: CGFloat = 28
        /// Точка под числом — «в этот день были звонки».
        static let historyDayDot: CGFloat = 4

        /// Ширина окна входящего. Высота не задаётся — окно подгоняется под
        /// содержимое.
        ///
        /// Фиксированная высота здесь уже стоила бага: в макете два состояния,
        /// 186 и 244 точки, но зафиксировать их значит получить пустую полосу
        /// между именем звонящего и кнопками всякий раз, когда содержимого
        /// меньше расчётного — например когда сервер не прислал имя.
        static let incomingCallPanelWidth: CGFloat = 320

        /// Подкраска поверхности окна входящего.
        ///
        /// Это второй рецепт стекла в приложении, и он заведён сознательно.
        /// Панель подкраску сняла 6 августа 2026, потому что та решала снятую
        /// задачу: стабильная светлота нужна была нашим цветам текста, а их
        /// больше нет. У окна входящего задача не снята — оно висит в случайной
        /// точке поверх произвольной CRM, и мелкий текст в нём читают один раз,
        /// быстро и под нагрузкой.
        ///
        /// Плотность задаёт **один** критерий: второй голос берёт 4.5:1 в обеих
        /// темах над худшей подложкой. Не два сразу — на этом панель потеряла
        /// три итерации (0.57 → 0.70 → 0.80), каждый раз потому, что целились
        /// попеременно в читаемость и в вид. Заметность окна плёнка не решает:
        /// за неё отвечает цветной якорь в шапке.
        ///
        /// **Число предварительное.** 0.30 — то, на чём стояла панель до
        /// отмены, взято отправной точкой. Замер живого окна над настоящей CRM
        /// не сделан, и до него это значение считать выбранным нельзя.
        static let incomingSurfaceTint: Double = 0.30

        /// Вертикальная набивка кнопок окна входящего.
        ///
        /// Одна на все три: до этого «Ответить» стояла на 9, «Отклонить» на 8,
        /// цифровая цель на 10 — три числа на одну и ту же вещь, и различались
        /// они на точку, то есть не различались. Кнопки при этом соседи по
        /// окну, и разная высота у них читается как сбой раскладки.
        static let incomingButtonPadding: CGFloat = 9

        // Шкала отступов: 2 / 4 / 6 / 8 / 12. Пять ступеней на всё, и всё, что
        // отступает, отступает одной из них.
        //
        // Две мелкие добавлены 5 августа 2026, когда выяснилось, что в вёрстке
        // живут одиннадцать разных значений — 1, 2, 3, 4, 5, 6, 8, 10, 12, 14.
        // Половина из них отличалась друг от друга на точку, то есть не
        // отличалась вовсе: разницу между 3 и 4 глаз не видит, а вот
        // необходимость каждый раз выбирать между ними — вполне.
        //
        // Вертикальные промежутки между ярусами панели сюда не входят: они
        // неравные по смыслу и живут поимённо в `Theme.Gap` (принцип 6).
        static let hairSpacing: CGFloat = 2
        static let tightSpacing: CGFloat = 4
        static let contentPadding: CGFloat = 12
        static let sectionSpacing: CGFloat = 8
        static let elementSpacing: CGFloat = 6

        /// Высота поля одной линии, когда линий две. Слот шапки делится на два
        /// таких поля, поэтому число связано с `headerHeight`, а не со шкалой.

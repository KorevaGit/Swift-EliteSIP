import SwiftUI

/// Разделы менеджерских настроек и то, какой из них открыт.
///
/// Появились вместе с переносом дизайна «Управления» на окно настроек: до этого
/// менеджерская страница была одна, разделы стояли на ней друг под другом, и
/// перечислять их было незачем.
///
/// **Почему страницу всё-таки разобрали на разделы.** Довод «одна короткая
/// страница ищется одним взглядом» был верен ровно до тех пор, пока страница
/// оставалась короткой. Она перестала: «Звук» отрастил самопроверку с её
/// состоянием, «Звонок» — три кнопки и предупреждение о пропавшем файле, — и
/// нижние разделы уехали за нижний край окна на ноутбучном экране. Дальше выбор
/// был между прокруткой и боковым списком, и список выигрывает: он не только
/// делит содержимое, но и **показывает целиком**, что в настройках вообще есть,
/// — а прокрутка это как раз прячет.
///
/// Взят тот же боковой список, что в «Управлении», а не свой: два окна одного
/// приложения, устроенные по-разному, читаются как собранные разными руками. По
/// этой же причине здесь нет ни одной своей константы — ширина сайдбара,
/// отступы половин и корпус приезжают из общих.
///
/// Вынесены из вью по той же причине, что и разделы «Управления»: окно собрано
/// системным `NSSplitViewController`, сайдбар и содержимое — два разных
/// контроллера с двумя разными деревьями SwiftUI, и общее состояние им негде
/// хранить, кроме как снаружи.
enum ManagerSection: String, CaseIterable, Identifiable {

    case audio, ringtone, appearance, support

    var id: String { rawValue }

    /// Порядок — по тому, как часто сюда заходят.
    ///
    /// «Звук» первым, потому что его правят при каждой смене наушников;
    /// «Техподдержка» последней, потому что туда идут, когда уже сломалось.
    var title: String {
        switch self {
        case .audio: "Звук"
        case .ringtone: "Звонок"
        case .appearance: "Оформление"
        case .support: "Техподдержка"
        }
    }

    /// Всё из имеющегося комплекта: значки рисуются руками ради Catalina, и
    /// перенос дизайна их дорисовку на себя не берёт (долг этапа 7).
    var symbol: String {
        switch self {
        case .audio: "mic.fill"
        case .ringtone: "bell"
        // Своего значка у оформления в комплекте нет. `gearshape` — не «тема»,
        // а «настройка вообще», и это признанная неточность: раздел опознаётся
        // подписью, а значок держит строку в колонке со всеми остальными.
        case .appearance: "gearshape"
        // Тот же, что у «Диагностики» в «Управлении», и повтор здесь безвреден:
        // рядом эти два окна не показываются — открытие «Управления» закрывает
        // настройки.
        case .support: "stethoscope"
        }
    }
}

/// Какой раздел настроек открыт. Общее состояние двух половин окна.
///
/// Класс, а не `@State`, по той же причине, что и `AdministrationRouter`:
/// сайдбар и содержимое живут в разных `NSHostingController`, и связать их
/// можно только объектом, который держит окно.
@MainActor
final class ManagerRouter: ObservableObject {

    @Published var section: ManagerSection = .audio
}

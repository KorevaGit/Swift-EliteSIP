#if DEBUG
import Foundation

/// Набор DTMF-макросов для отладки.
///
/// Сетка макросов занимает в панели всё место бывшего дайлпада, и проверять её
/// на пустом списке нельзя: без макросов панель короче на всю сетку, то есть
/// проверяется как раз то состояние, которого у работающего сотрудника не
/// бывает.
///
/// Только в отладочной сборке и только когда макросов нет вовсе: как только
/// администратор заведёт настоящие, этот код молчит навсегда. Подписи взяты
/// разной длины намеренно — короткие, длинные и составные ломают сетку
/// по-разному.
extension AppModel {

    func seedDebugMacrosIfNeeded() {
        guard settings.dtmf.macros.isEmpty else { return }

        // не переводится: подпись макроса вводит администратор, а эти восемь
        // — отладочная заглушка, которой в сборке продукта нет вовсе.
        settings.dtmf.macros = [
            .init(title: "Перевод", sequence: "*2"),
            .init(title: "Отдел продаж", sequence: "101"),
            .init(title: "Склад", sequence: "102"),
            .init(title: "Бухгалтерия", sequence: "103"),
            .init(title: "Конференция", sequence: "*3,1"),
            .init(title: "Гудок", sequence: "0"),
            .init(title: "Секретарь", sequence: "100"),
            .init(title: "Тех. отдел", sequence: "104"),
        ]

        append(level: .debug, message: "отладка: заведены восемь макросов для проверки сетки")
    }
}
#endif

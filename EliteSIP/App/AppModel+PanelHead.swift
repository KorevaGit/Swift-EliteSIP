import Foundation
import SIPCore

/// Голова панели: капсула профиля и слот беды.
///
/// Вынесено из `AppModel` отдельно, потому что это единственное место, где
/// состояние регистрации переводится с языка протокола на язык оператора.
/// Внутри `AppModel` живут `SIPRegistrationState`, путь сети и настройки — три
/// разных источника, — а панели нужен один ответ: что показать в строке.
extension AppModel {

    /// Что мешает работать. `nil` — не мешает ничто.
    ///
    /// Порядок разбора здесь и есть приоритет: сначала то, что чинит человек,
    /// потом то, что чинится само. Иначе «нет сети» перекрывало бы «профиль без
    /// пароля», и администратор, пришедший чинить машину, видел бы жалобу на
    /// сеть при исправной сети.
    enum Trouble: Equatable {

        /// Не хватает настройки: учётки или пароля. Чинит администратор.
        case setup(String)
        /// Пути наружу нет вовсе.
        case noNetwork
        /// Сервер ответил отказом.
        case failed(reason: String)
        /// Регистрация идёт дольше, чем следует.
        case connecting

        /// Короткая причина — то, что стоит в строке, и всё, что о беде
        /// говорит панель.
        ///
        /// Короткая не ради красоты: в 270 точках рядом с капсулой и
        /// шестерёнкой слоту достаётся около 150, и всё, что длиннее, там
        /// обрезается.
        ///
        /// Подробностей — времени повтора, кода ответа, имени профиля — в
        /// панели нет вовсе, и они не потеряны: всё это пишет журнал, и пишет
        /// подробнее, чем поместилось бы в строку. Подсказка при наведении
        /// была бы вторым местом с той же правдой, причём местом, которого на
        /// Catalina не существует (`compatHelp` там пустой).
        var text: String {
            switch self {
            case .setup(let hint): hint
            case .noNetwork: NSLocalizedString("Нет сети", comment: "состояние в шапке панели")
            case .failed(let reason): reason
            case .connecting: NSLocalizedString("Подключение…", comment: "состояние в шапке панели")
            }
        }

        /// Ведёт ли надпись в настройки.
        ///
        /// Ведёт только то, что чинит человек. Сеть и сервер починятся сами, и
        /// делать вид, что нажатие поможет, — обман.
        var opensSettings: Bool {
            if case .setup = self { return true }
            return false
        }

        /// Цвет подписи задаётся не здесь, но признак «это авария» — здесь:
        /// `connecting` беда временная и красным гореть не должна.
        var isFailure: Bool { self != .connecting }
    }

    /// Что показывает слот между капсулой и шестерёнкой.
    ///
    /// Отключение вручную сюда не попадает: это не беда, а решение оператора, и
    /// говорит о нём серая точка в капсуле.
    var trouble: Trouble? {
        if isOfflineByChoice { return nil }

        // Настройка — раньше всего остального: см. комментарий к `Trouble`.
        if let hint = setupHint { return .setup(hint) }

        switch registration {
        case .failed(let reason, _):
            // Время следующей попытки в строку не идёт: она короткая, а в
            // журнале эта же неудача уже записана вместе с задержкой повтора.
            return .failed(reason: reason)
        case .registering:
            // Обычное подключение занимает доли секунды, и надпись на нём
            // только мигала бы — при каждом запуске, смене сети и пробуждении.
            // Поэтому слот молчит, пока подключение не затянулось; затягивание
            // и есть то, о чём стоит сказать.
            return isRegistrationSlow ? .connecting : nil
        case .idle:
            // Сеть проверяется здесь, а не первой: пока регистрация жива,
            // пропавший путь ещё ничего не значит — агент переживает смену сети
            // чаще, чем мы успеваем о ней сообщить.
            return lastNetworkPathIsSatisfied ? nil : .noNetwork
        case .registered, .unregistering:
            return nil
        }
    }

    /// Номер в капсуле — крупным планом.
    var panelStatusTitle: String {
        isOfflineByChoice
            ? NSLocalizedString("Отключён", comment: "состояние в шапке панели")
            : settings.account.username
    }

    /// Пометка профиля рядом с номером. `nil` — показывать нечего.
    ///
    /// Без неё два профиля одного добавочного — «172 · Офис» и «172 ·
    /// Удалённо» — в свёрнутом виде неразличимы, а различаются они адресом
    /// сервера, то есть тем, дозвонится оператор или нет. Пометка стоит вторым
    /// планом и ужимается первой: номер важнее, и место она занимает по
    /// остаточному принципу.
    var panelStatusLabel: String? {
        guard !isOfflineByChoice else { return nil }
        let label = settings.profiles.active.label
        return label.isEmpty ? nil : label
    }

    /// Подпись профиля в списке: номер и пометка одной строкой.
    ///
    /// Не `profileTitle`: тот показывает пометку **вместо** номера, и в списке
    /// из трёх профилей одного добавочного номера не было бы видно вовсе.
    func profileMenuTitle(_ profile: SIPProfile) -> String {
        let number = profile.account.username.isEmpty
            ? NSLocalizedString("без номера", comment: "профиль без добавочного в списке")
            : profile.account.username
        return profile.label.isEmpty ? number : "\(number) · \(profile.label)"
    }

    /// Можно ли раскрыть список профилей.
    ///
    /// В разговоре нельзя: и смена профиля, и отключение снимают регистрацию и
    /// закрывают диалоги (M6b). Капсула при этом остаётся на месте и остаётся
    /// читаемой — исчезает только шеврон, потому что нажимать больше не на что.
    var canOpenProfileMenu: Bool { canSwitchProfile }

    /// Уйти с линии по решению оператора.
    ///
    /// Признак живёт только в памяти и в настройки не пишется: «выключил в
    /// пятницу, в понедельник не понял, почему тихо» — это не то состояние, в
    /// котором софтфон должен встречать следующий рабочий день. При запуске
    /// приложение снова выходит на линию само.
    func goOffline() async {
        // Повторный выбор того же пункта — не событие. Без этой проверки
        // журнал набирался строками «оператор ушёл с линии» подряд, и разобрать
        // по нему, что именно нажимали, становилось нельзя.
        guard !isOfflineByChoice else { return }

        guard canSwitchProfile else {
            append(level: .warning, message: "отключение недоступно: идёт разговор")
            return
        }
        isOfflineByChoice = true
        append(level: .info, message: "оператор ушёл с линии до конца сеанса")
        await disconnect()
    }

    /// Вернуться на линию — выбором профиля в том же списке.
    ///
    /// Отдельного пункта «Подключиться» нет: возврат на линию это и есть ответ
    /// на «под каким номером работать», а он уже задан списком профилей.
    func goOnline(profile id: UUID) async {
        isOfflineByChoice = false

        if id != settings.profiles.activeID {
            await selectProfile(id)
        }

        // Подключение здесь, а не внутри `selectProfile`, и это не
        // подстраховка. `selectProfile` поднимает регистрацию только если она
        // была до смены: он обслуживает и настройки, где отключённый софтфон
        // после смены профиля обязан остаться отключённым. Про то, что мы
        // пришли из «Отключён», он не знает.
        //
        // Именно на этом ловился баг: после «Отключён» выбор *другого* профиля
        // менял его молча и не подключался, а выбор *того же* — подключался,
        // потому что `selectProfile` выходил на первом же guard. В журнале это
        // выглядело как «профиль: Лаба» без единой строки про REGISTER.
        //
        // Повторного подключения не боимся: `connectIfPossible` молчит, когда
        // агент уже поднят.
        await connectIfPossible()
    }
}

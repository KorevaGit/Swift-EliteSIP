/// Заводская настройка: что приложение знает о рабочих местах ещё до первого
/// запуска.
///
/// Появилась в этапе 9 вместе с окном первоначальной настройки. До неё свежая
/// установка не знала ничего: `SIPProfileList` восстанавливал пустой профиль,
/// «Управление» стояло без пароля и открытое всякому, а десяток рабочих мест
/// настраивали руками по одному.
///
/// **Разделена на две половины по одному признаку — что можно держать в Git.**
///
/// - **Заводских предустановок больше нет.** Макросы, очереди и адрес АТС
///   держались исходником в репозитории — по правилу «в Git нельзя пароли, а
///   номера можно». С переходом на ключи это правило перестало быть нужным:
///   всё, что описывает контору, приезжает после активации и только после неё,
///   а до ввода ключа бинарник не знает о ней ничего, кроме адреса канала.
/// - `Secrets` — административный пароль и код восстановления. Единственное,
///   что лежит **вне Git**, в `Config/provisioning.local.json` (файл попадает
///   под `*.local.json` в `.gitignore`), и вшивается в релизный бандл шагом
///   сборки — M7e, пункт 7.
///
/// Разбор `.app` выдаёт административный пароль открытым текстом, один и тот же
/// на всех машинах. Это принято сознательно 15 августа 2026: применение
/// внутреннее, распространения нет, а свежая машина без пароля хуже — она стоит
/// с настройками, открытыми любому оператору.
enum Provisioning {

    /// Секреты рабочего места. Читаются из бандла, в Git не лежат.
    struct Secrets: Decodable, Sendable {

        /// Административный пароль. Один на все машины конторы.
        var adminPassword: String

        // Кода восстановления здесь больше нет.
        //
        // Он лежал открытым текстом в бандле каждого приложения, то есть
        // «восстановление пароля» работало у всякого, кто вскрыл `.app`.
        // Долг, который `docs/admin.md` называл прямо, закрылся сам собой:
        // актуальный пароль показывает панель, потому что оттуда он и
        // приезжает.

        /// Канал обновлений (M7h).
        ///
        /// Здесь по той же причине, что и пароль: адрес не секрет, а вот пара
        /// авторизации — секрет, и в Git ей нельзя. Раз они всё равно едут
        /// вместе, разносить их по двум местам значит завести второй файл с
        /// теми же правилами.
        ///
        /// Необязателен намеренно: отладочная сборка на машине без конфига
        /// должна собираться и работать, просто без обновлений. Release без
        /// него не собирается вовсе — это проверяет `Tools/embed-provisioning.sh`.
        var updates: UpdateChannel?

        /// Учётные данные для файла настроек.
        ///
        /// Соли случайные, поэтому у каждой машины хэши свои, хотя пароль общий:
        /// одинаковый файл настроек на двадцати местах дал бы двадцать
        /// одинаковых `loginHash`, и подобравший один подобрал бы все.
        func credential() throws -> AdminCredential {
            try AdminCredential(password: adminPassword)
        }
    }

    /// Откуда рабочее место берёт обновления.
    ///
    /// Пара логин-пароль **одна на все сборки** и лежит в том же бандле, что и
    /// всё остальное. Что это даёт, сказано прямо в `docs/release.md`: защиту от
    /// случайного обхода и индексации, но не от того, у кого уже есть копия
    /// приложения. Настоящую защиту канала даёт подпись EdDSA, а не эта пара.
    struct UpdateChannel: Decodable, Sendable {

        /// Корень канала, без имени фида: `https://get.elitesip.vip`.
        ///
        /// Имя фида дописывается по срезу — приложение своё исполняемое
        /// семейство знает, а Sparkle выбирать между срезами не умеет.
        var baseURL: String

        var user: String
        var password: String

        /// Адрес appcast для того среза, которым собрано это приложение.
        ///
        /// `#if arch` разрешается для каждого среза отдельно, поэтому в
        /// universal-бандле каждая половина получит свой адрес — чего нельзя
        /// добиться значением в `Info.plist`, одном на оба.
        var feedURL: URL? {
            #if arch(x86_64)
            let slice = "x86_64"
            #elseif arch(arm64)
            let slice = "arm64"
            #else
            let slice = "unknown"
            #endif
            return URL(string: baseURL.hasSuffix("/") ? "\(baseURL)appcast-\(slice).xml"
                                                      : "\(baseURL)/appcast-\(slice).xml")
        }

        /// Адрес файла предустановок (M9).
        ///
        /// Тот же канал и та же пара авторизации, что у обновлений: второй
        /// секрет в бандле ничего не добавил бы — оба всё равно видны через
        /// `strings`, а настоящую защиту линии даёт подпись Ed25519.
        ///
        /// В отличие от appcast, среза здесь нет: файл предустановок один на
        /// оба. Машина ищет в нём себя по идентификатору предустановки, а не по
        /// тому, каким процессором собрана.
        var presetsURL: URL? {
            URL(string: root + "presets/current.json")
        }

        /// Адрес помашинного объекта: `access/<id>` или `revoked/<id>`.
        ///
        /// Приставка приходит сюда строкой, а не перечислением: их две, обе
        /// живут в контракте с панелью, и заводить ради них тип значило бы
        /// держать третье место, где это же написано.
        func machineURL(prefix: String, installationID: String) -> URL? {
            guard !installationID.isEmpty else { return nil }
            return URL(string: root + prefix + "/" + installationID)
        }

        private var root: String {
            baseURL.hasSuffix("/") ? baseURL : baseURL + "/"
        }
    }

    // Заводских предустановок здесь больше нет.
    //
    // Они держали в бандле адреса АТС, макросы и очереди — то есть настройки
    // конторы в исходнике, который уезжает вместе с приложением к каждому, кто
    // его получал. С переходом на ключи всё это приезжает после активации и
    // только после неё: до ввода ключа бинарник не знает о конторе ничего,
    // кроме адреса канала раздачи. Разбор — elitesupport/docs/DECISIONS.md,
    // «Бинарник без данных конторы».
}

// MARK: - Чтение

extension Provisioning {

    /// Имя ресурса в бандле. Кладётся туда шагом сборки из
    /// `Config/provisioning.local.json`.
    private static let resourceName = "provisioning"

    /// Секреты этой сборки. `nil` — конфига в бандле нет.
    ///
    /// Отладочная сборка получает заглушку вместо `nil`: без пароля мастер
    /// непроходим, а проходить его до релиза надо. Релизная не получает ничего —
    /// и это не забытая ветка, а требование к сборке: выпуск без конфига обязан
    /// ронять сборку, а не подставлять умолчания (M7e, пункт 7). Приложение,
    /// собранное без пароля, внешне рабочее, но каждая машина из него встаёт с
    /// «Управлением», открытым всякому.
    static var secrets: Secrets? {
        if let url = Bundle.main.url(forResource: resourceName, withExtension: "json"),
            let decoded = decodedSecrets(at: url)
        {
            return decoded
        }
        #if DEBUG
            // Отладочная сборка читает конфиг из дерева проекта.
            //
            // В бандл он попадает только в релизе (M7e, пункт 7), и без этого
            // отладочная сборка сверяла бы пропуск с заглушкой — то есть
            // настоящий административный пароль в ней **не подходил**, а
            // проверяющий видел «пароль не подошёл» и не имел способа узнать,
            // почему. Именно это и случилось 17 августа 2026.
            //
            // Путь берётся от `#filePath` — от места этого исходника, а не от
            // рабочего каталога: приложение запускают и из Xcode, и из Finder, и
            // из терминала, и рабочий каталог у них разный. В релизе ветка не
            // компилируется вовсе, так что путь машины сборщика в выпуск не
            // уезжает.
            if let decoded = decodedSecrets(at: localConfigURL) { return decoded }
            // не переводится: пароль-заглушка на случай, когда конфига нет и в
            // дереве, — его не читают с экрана, его вводят по памяти те, кто
            // собирает приложение.
            return Secrets(adminPassword: "стенд")
        #else
            return nil
        #endif
    }

    private static func decodedSecrets(at url: URL) -> Secrets? {
        guard let data = try? Data(contentsOf: url) else { return nil }
        return try? JSONDecoder().decode(Secrets.self, from: data)
    }

    #if DEBUG
        /// `Config/provisioning.local.json` в дереве проекта.
        ///
        /// Три уровня вверх от `EliteSIP/Services/Provisioning.swift` — это корень
        /// репозитория.
        private static var localConfigURL: URL {
            URL(fileURLWithPath: #filePath)
                .deletingLastPathComponent()  // Services
                .deletingLastPathComponent()  // EliteSIP
                .deletingLastPathComponent()  // корень
                .appendingPathComponent("Config/provisioning.local.json")
        }
    #endif
}

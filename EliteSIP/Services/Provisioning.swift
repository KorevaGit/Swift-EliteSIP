extension Provisioning.FactoryPreset {

    /// Рабочее место менеджера EliteSochi.
    ///
    /// Макросы — боевые коды перевода, полученные 16 августа 2026. Уходят
    /// тонами, а не `REFER`, хотя настоящий перевод у клиента есть с M5:
    /// решение сознательное, так поведение в точности повторяет привычный
    /// менеджерам старый клиент. Цена записана в `docs/ROADMAP.md`, раздел M4 —
    /// приложение не узнаёт, что звонок увели.
    ///
    /// `КОНФЕРЕНЦИЯ · *3` из старого клиента здесь нет намеренно: это ровно
    /// `ConferenceSettings.featureCode`, у которого в приложении своё действие,
    /// а две кнопки на одно и то же расходятся с состоянием.
    // не переводится: имя предустановки, подписи макросов и название очереди —
    // текст администратора, а не приложения. Решение этапа 8: их вводит человек
    // под свою АТС, и переводить их не наше дело. Русский интерфейс или
    // английский, «Саммер Бэй» остаётся «Саммер Бэй» — это название объекта.
    static let manager = Self(
        name: "Менеджер",
        // Боевые адреса, названы 16 августа 2026. Внутренний — тот же, что
        // стоял примером в `docs/profiles.md`: пример был боевым.
        officeHost: "192.168.1.2",
        remoteHost: "crm.elitesochi.com",
        // `transfersCall` у всех трёх: `*02` — Attended Transfer боевого
        // сервера (`core show features`, 30 июля 2026), и нажатие такой клавиши
        // уводит клиента к коллеге. Без признака приложение об этом не знает, и
        // в истории перевода не видно — цена, названная в `docs/ROADMAP.md`,
        // раздел M4. Признак её закрывает наполовину: состояние линии
        // по-прежнему ведёт сервер, но сам факт перевода в записи появляется.
        macros: [
            // Все три помечены переводом: это коды Attended Transfer боевой АТС,
            // и без пометки история не покажет, куда делся клиент.
            .init(title: "Юрист", sequence: "*029999#", transfersCall: true),
            .init(title: "Саммер Бэй", sequence: "*029998#", transfersCall: true),
            .init(title: "ОП", sequence: "*029997#", transfersCall: true),
        ],
        queueTitle: "🔥Горячая раздача🔥",
        queueNumbers: [
            "1001", "1002", "12", "1220", "1221", "1222", "1223", "1224", "1225",
            "1226", "15", "1550", "1551", "1552", "1553", "1554", "1555", "1556",
            "2221", "2225", "2226", "2227", "2331", "2929", "3030", "3121", "3122",
            "3123", "3221", "3222", "3223", "3321", "3322", "3323", "45", "4551",
            "4552", "4553", "4557",
        ]
    )

    /// Стенд — предустановка отладочной сборки.
    ///
    /// Нужна ровно затем, чтобы мастер первого запуска проходился целиком до
    /// релиза: конфига с секретами в отладке нет, а без предустановки экран
    /// «Первый пользователь» показывал бы пустой список и непроверяемый
    /// пропуск. Адрес — петля лаборатории, макросы и очереди выдуманные:
    /// это стенд, а не рабочее место.
    static let laboratory = Self(
        name: "Лаборатория",
        // Петля в обе половины пары: стенд не переезжает, и стучать в
        // `127.0.0.1` бессмысленно — тот же довод, что у `LabPreset.site`.
        officeHost: "127.0.0.1",
        remoteHost: "127.0.0.1",
        macros: [
            .init(title: "Стенд", sequence: "*1#"),
        ],
        queueTitle: "Стендовая раздача",
        queueNumbers: ["2929"]
    )
}

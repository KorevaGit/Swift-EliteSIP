import Foundation

/// Язык интерфейса.
///
/// **Хранится не в `AppSettings`, а там же, где его держит сама macOS** — в
/// ключе `AppleLanguages` собственного домена приложения. Причина в порядке
/// событий: Foundation читает этот ключ раньше, чем выполнится хоть строка
/// нашего кода и будет прочитан файл настроек, и показанный язык всегда берётся
/// оттуда. Вторая копия в `AppSettings` означала бы два значения, которые
/// расходятся при первом же импорте настроек с чужой машины — и показывают при
/// этом разное: файл говорит одно, окно другое.
///
/// Из этого следует и то, что язык не ездит в предустановке. Это правильно:
/// предустановка настраивает рабочее место — АТС, макросы, очереди, — а язык
/// выбирает тот, кто за этим местом сидит, и меняется он вместе с человеком, а
/// не вместе с рабочим местом.
enum LanguageSetting: String, CaseIterable, Identifiable {

    /// Как у всей системы. Ключ в домене приложения при этом снимается вовсе —
    /// то же состояние, что у свежей установки.
    case system

    case russian = "ru"
    case english = "en"

    var id: String { rawValue }

    /// Подпись в переключателе.
    ///
    /// Название языка написано на нём самом — так их подписывает и macOS в
    /// «Языке и регионе». Иначе выбор нельзя сделать из положения, в которое
    /// сам и попал: человек, у которого приложение говорит на незнакомом ему
    /// языке, ищет в списке слово, которое узнаёт, а не перевод этого слова.
    var title: String {
        switch self {
        case .system:
            return NSLocalizedString("Системный", comment: "язык интерфейса — как у системы")
        // не переводится: название языка пишется на нём самом.
        case .russian:
            return "Русский"
        case .english:
            return "English"
        }
    }

    /// Что выбрано сейчас.
    ///
    /// Читается только домен приложения, а не `UserDefaults.standard`: у
    /// стандартных настроек в списке поиска стоит и общесистемный домен, и
    /// оттуда `AppleLanguages` вернётся всегда — язык системы приехал бы как
    /// «выбранный вручную», и «Системный» не выбирался бы никогда.
    static var current: LanguageSetting {
        guard let identifier = Bundle.main.bundleIdentifier,
              let domain = UserDefaults.standard.persistentDomain(forName: identifier),
              let chosen = (domain[key] as? [String])?.first
        else { return .system }

        // Сравнение по началу строки: система хранит здесь полные метки вида
        // «ru-RU», а выбираем мы язык, а не регион.
        return allCases.first { $0 != .system && chosen.hasPrefix($0.rawValue) } ?? .system
    }

    /// Запомнить выбор.
    ///
    /// Записывается синхронно и до перезапуска. Перезапуск запускает новый
    /// процесс раньше, чем завершается старый, и незаписанный выбор новый
    /// процесс просто не увидел бы — приложение поднялось бы на прежнем языке,
    /// а человек решил бы, что переключатель не работает.
    func apply() {
        let defaults = UserDefaults.standard
        switch self {
        case .system:
            defaults.removeObject(forKey: Self.key)
        case .russian, .english:
            defaults.set([rawValue], forKey: Self.key)
        }
        defaults.synchronize()
    }

    private static let key = "AppleLanguages"
}

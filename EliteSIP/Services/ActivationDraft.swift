import Foundation
import PanelLink

/// Распечатанный пакет активации, переживающий закрытый мастер.
///
/// **Ключ одноразовый, и сгорает он на «Проверить ключ», а не на «Далее».**
/// Так устроен канал раздачи: Worker столбит объект условной записью *до* того,
/// как отдать его, — иначе два одновременных запроса по одному ключу получили
/// бы пакет оба. Цена там названа прямо и принята: оборвавшаяся закачка сжигает
/// ключ.
///
/// Чего в той цене не было — это закрытого мастера. Человек нажимал «Проверить
/// ключ», видел своё имя, закрывал окно (передумал, сработала перезагрузка,
/// отвлекли) — и ключ был сожжён, а машина не настроена. Панель при этом
/// показывала «ждём активации»: она видит отметку, а машина ей о себе ещё не
/// сказала. Второй раз тот же ключ не открывался никогда, и выход был один —
/// просить новый.
///
/// Черновик закрывает ровно эту дыру и ничего больше. Пакет уже у нас в руках,
/// повторный заход на канал не нужен — нужно только не потерять то, что
/// приехало. Поэтому распечатанное ложится на диск сразу за успешной проверкой,
/// поднимается при следующем открытии мастера и стирается в тот миг, когда
/// настройка применилась.
///
/// **Одноразовость ключа это не ослабляет.** Сгоревший ключ остаётся сгоревшим
/// для всех: черновик лежит на той же машине, в каталоге приложения под 0600, и
/// на чужой не поможет — там его попросту нет.
enum ActivationDraftStore {

    /// Что сохраняем: сам пакет, помашинный доступ, забранный тем же заходом, и
    /// ключ, которым всё это открыли.
    ///
    /// Ключ здесь — вопреки правилу «ключ нигде не сохраняется». Правило это
    /// имело смысл, пока ключ был пропуском: незачем держать на диске то, чем
    /// открывается пакет. К этому моменту он уже сожжён и не открывает ничего;
    /// зато он показывается в поле, а мастер, поднявшийся с чужим на вид
    /// черновиком и пустым полем ключа, объяснить себя не может.
    struct Draft: Codable {
        var key: String
        var package: ActivationPackage
        var access: MachineAccess?
        var savedAt: Date
    }

    /// Черновик живёт столько же, сколько сам пакет в канале, — двое суток.
    ///
    /// Не дольше: пролежавшая неделю копия SIP-пароля на машине, которую так и
    /// не настроили, — это не помощь, а забытая учётная запись. Срок тот же,
    /// что у пакета в бакете, и по той же причине: за этим порогом человеку в
    /// любом случае выпишут новый ключ.
    static let lifetime: TimeInterval = 48 * 60 * 60

    private static var fileURL: URL {
        SettingsStore.fileURL
            .deletingLastPathComponent()
            .appendingPathComponent("activation-draft.json")
    }

    static func save(key: String, package: ActivationPackage, access: MachineAccess?) {
        let draft = Draft(key: key, package: package, access: access, savedAt: Date())
        do {
            let url = fileURL
            try FileManager.default.createDirectory(
                at: url.deletingLastPathComponent(), withIntermediateDirectories: true
            )
            let encoder = JSONEncoder()
            encoder.dateEncodingStrategy = .iso8601
            try encoder.encode(draft).write(to: url, options: .atomic)
            // 0600 после каждой записи, а не один раз: `.atomic` пишет во
            // временный файл и переименовывает его на место, то есть права у
            // файла каждый раз новые, взятые из umask. Тот же порядок, что у
            // файла настроек, и по той же причине — внутри пароль SIP.
            try? FileManager.default.setAttributes(
                [.posixPermissions: 0o600], ofItemAtPath: url.path
            )
        } catch {
            // Молча: не сохранившийся черновик — потеря удобства, а не отказ
            // настройки. Мастер в эту минуту держит пакет в памяти и доведёт
            // дело до конца.
        }
    }

    /// Поднимает черновик, если он есть и не просрочен. Просроченный стирается
    /// здесь же: файл с паролем SIP не должен переживать свою полезность.
    static func load() -> Draft? {
        guard let data = try? Data(contentsOf: fileURL) else { return nil }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        guard let draft = try? decoder.decode(Draft.self, from: data) else {
            // Испорченный — стереть, а не таскать: разобрать его уже нечем, а
            // мешать он будет каждой следующей загрузке.
            clear()
            return nil
        }
        guard Date().timeIntervalSince(draft.savedAt) < lifetime else {
            clear()
            return nil
        }
        return draft
    }

    static func clear() {
        try? FileManager.default.removeItem(at: fileURL)
    }
}

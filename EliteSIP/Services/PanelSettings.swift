import Foundation

extension AppSettings {

    /// Что машина знает о панели EliteSIP (M9).
    ///
    /// Приезжает пакетом активации и живёт до сброса машины. Пустой блок
    /// означает «машину поднимали не ключом», и это обычное состояние: пути
    /// «Вручную» и «Загрузить конфигурацию» никуда не делись.
    ///
    /// **Обратной связи от машины к панели нет и не будет.** Панель узнаёт о
    /// рабочих местах только по следам, которые оставляет раздача файлов, — а
    /// приложение к ней не обращается вовсе. Поэтому здесь нет ни адреса
    /// панели, ни ключа доступа к ней: обращаться некуда и незачем.
    struct PanelSettings: Codable, Sendable, Equatable {

        /// Единственное, по чему панель вообще узнаёт эту машину.
        ///
        /// Приезжает в пакете активации и сообщается при каждом запросе за
        /// файлом предустановок. **Не теряется при сбросе профиля**: профиль —
        /// это учётная запись, а идентификатор — это машина.
        var installationID: String = ""

        /// Предустановка, под которой машина живёт.
        ///
        /// Ищет она себя в файле по `id`, а **не по имени**: имя переименовывают,
        /// и поиск по нему разорвал бы связь у всех машин разом. Имя хранится
        /// рядом только затем, чтобы было что показать человеку.
        var presetID: String = ""
        var presetName: String = ""

        /// Применённая ревизия. Ноль означает «ни одной ещё не применяли».
        var appliedRevision: Int = 0
        var appliedAt: Date?

        /// Режим машины: слушать панель или жить своим умом.
        var mode: Mode = .manual

        /// Режим машины — решение этапа 5 работ по панели.
        ///
        /// Действует на машину целиком, а не на отдельные настройки: половинчатый
        /// режим означал бы, что администратор не может ответить на вопрос
        /// «управляется ли это рабочее место», не перебрав два десятка полей.
        enum Mode: String, Codable, Sendable {

            /// Файл предустановок применяется. Управляемые поля показываются,
            /// но не редактируются локально.
            case managed

            /// Файл не применяется ни в чём. Это же — состояние машины, которую
            /// поднимали не ключом.
            case manual
        }

        /// Слушает ли машина панель.
        ///
        /// Отсюда выводится `CallGuardPolicy.isServerManaged`, и **только
        /// отсюда**: полем из файла он не приезжает, потому что это был бы
        /// второй источник одного факта. Поле заведено в M7c как «место под
        /// вариант 1» и до сих пор всегда было `false`; теперь оно наконец
        /// получает смысл.
        var isManaged: Bool { mode == .managed && !presetID.isEmpty }

        /// Знает ли панель об этой машине вообще.
        var isActivated: Bool { !installationID.isEmpty }
    }
}

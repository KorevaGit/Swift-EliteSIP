/// Кто из говорящих на нашем порту — собеседник.
///
/// На открытый UDP-порт прилетает что угодно. Ядро отсекает датаграммы не от
/// адреса АТС — сокет RTP «подключён», — но внутри этого адреса источник
/// опознаётся только полем SSRC, и полагаться на то, что он один, нельзя в обе
/// стороны:
///
/// - **Принимать всех** значит отдать оператору чужой поток вперемешку с
///   настоящим. Номера последовательности у потоков свои, и джиттер-буфер
///   склеит их в кашу, не заметив подмены.
/// - **Отказывать всем, кроме первого**, значит однажды замолчать навсегда.
///   Asterisk меняет SSRC, когда меняется мост на его стороне: после перевода,
///   после входа в конференцию, при переходе на музыку ожидания. Проверка в
///   одну строку стоила бы разговора, который оборвался ровно в момент, ради
///   которого его переводили.
///
/// Отсюда середина: чужой источник отбрасывается, но если он приходит подряд и
/// настойчиво, а прежний замолчал, — значит поток действительно сменился, и
/// новый признаётся своим.
///
/// Тип чистый и без замков: решение зависит только от последовательности
/// пришедших SSRC, и проверяется оно тестом, а не прослушиванием разговора.
/// Замок остаётся снаружи, у того, кто зовёт, — как и у всего остального
/// состояния `MediaSession`.
struct RemoteSourceFilter: Sendable {

    /// Что делать с пакетом.
    enum Verdict: Sendable, Equatable {
        /// Наш поток. Обычный случай.
        case known
        /// Чужой источник — выбросить, ничего никому не говоря.
        case foreign
        /// Источник сменился по-настоящему: пакет принять, но буфер выбросить.
        case adopted
    }

    /// Сколько пакетов подряд нужно новому источнику, чтобы его признали.
    ///
    /// Пять — это сто миллисекунд при обычных двадцати на пакет. Одиночная
    /// подмена столько не живёт, настоящая смена источника проходит незаметно:
    /// четыре потерянных кадра закрывает сокрытие потерь, и на слух это ровно
    /// то же, что одна короткая заминка сети.
    static let adoptionRun = 5

    /// SSRC, признанный своим. `nil` — первого пакета ещё не было.
    private(set) var accepted: UInt32?

    /// Кандидат на смену и сколько его пакетов пришло подряд.
    private var candidate: UInt32?
    private var candidateRun = 0

    init() {}

    /// Разбирает очередной SSRC.
    mutating func admit(ssrc: UInt32) -> Verdict {
        guard let accepted else {
            // Первый пакет разговора и задаёт источник. Спрашивать тут нечего:
            // до него мы не знаем про собеседника вообще ничего.
            self.accepted = ssrc
            return .known
        }

        if accepted == ssrc {
            // Прежний источник жив — значит счёт кандидату надо обнулить.
            // Иначе чужой поток, идущий вперемешку с настоящим, однажды
            // накопил бы свои пять пакетов и вытеснил собеседника.
            candidate = nil
            candidateRun = 0
            return .known
        }

        if candidate == ssrc {
            candidateRun += 1
        } else {
            candidate = ssrc
            candidateRun = 1
        }

        guard candidateRun >= Self.adoptionRun else { return .foreign }

        self.accepted = ssrc
        candidate = nil
        candidateRun = 0
        return .adopted
    }
}

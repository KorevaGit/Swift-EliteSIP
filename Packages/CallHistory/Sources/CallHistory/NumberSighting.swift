import Foundation

/// Номер, с которого на эту машину приходили вызовы, и когда это было в
/// последний раз.
///
/// Заведён под подсказки словаря очередей: администратор не может узнать номера
/// очередей ниоткуда, кроме как спросив у заказчика, — боевой Asterisk у нас на
/// чтение, — а ошибка в цифре не проявляется никак: вызов просто остаётся без
/// названия, молча. Подсказка предлагает то, что действительно приходило.
///
/// Не запись звонка: ни собеседника, ни исхода, ни длительности здесь нет.
/// Словарю нужен номер, а истории на этом экране не место.
public struct NumberSighting: Sendable, Hashable, Identifiable {

    public var number: String
    public var lastCall: Date

    /// Сколько раз приходил. Отличает настоящую очередь от единственного
    /// звонка с внутреннего добавочного, который в словарь не нужен.
    public var count: Int

    public var id: String { number }

    public init(number: String, lastCall: Date, count: Int) {
        self.number = number
        self.lastCall = lastCall
        self.count = count
    }

    /// Сколько в номере цифр. Всё остальное — плюсы, скобки и дефисы — на
    /// длину не влияет: один и тот же номер приходит записанным по-разному.
    public var digitCount: Int {
        number.reduce(into: 0) { $0 += $1.isNumber ? 1 : 0 }
    }
}

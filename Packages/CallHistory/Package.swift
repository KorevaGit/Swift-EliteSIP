// swift-tools-version: 6.0
import PackageDescription

// CallHistory — локальная история звонков: хранилище, срок хранения и выборки.
//
// Отдельный пакет по той же причине, что Diagnostics: здесь есть что проверять
// без AppKit и без живой АТС. Схема записи, уборка по сроку, поведение при
// испорченном файле и при падении приложения посреди разговора — всё это
// проверяется тестом на временном каталоге, а не наблюдением за рабочим местом
// в течение квартала.
//
// Хранилище — SQLite из системы (`import SQLite3`), без сторонних зависимостей:
// библиотека есть в SDK начиная задолго до Catalina, а приёмка требует, чтобы
// десять тысяч записей не замедляли открытие панели. Плоский файл этого не
// даёт: фильтр по направлению и «последние двести» превращаются в чтение всего
// файла. Разбор альтернатив — в docs/history.md.
//
// О SIP пакет не знает ничего: номер, логин и причина завершения приезжают
// строками. Иначе зависимость пошла бы в обратную сторону, а истории всё равно
// нечего делать с диалогами и транзакциями.
let package = Package(
    name: "CallHistory",
    platforms: [.macOS(.v10_15)],
    products: [
        .library(name: "CallHistory", targets: ["CallHistory"])
    ],
    targets: [
        .target(
            name: "CallHistory",
            swiftSettings: [.swiftLanguageMode(.v6)]
        ),
        .testTarget(
            name: "CallHistoryTests",
            dependencies: ["CallHistory"],
            swiftSettings: [.swiftLanguageMode(.v6)]
        ),
    ]
)

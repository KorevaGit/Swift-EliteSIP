import Foundation

/// Отказы при разборе того, что пришло от панели.
///
/// Список короткий намеренно. Он не описывает, что именно пошло не так внутри
/// криптографии, — он описывает то, что человеку осмысленно показать.
public enum PanelLinkError: Error, Equatable, LocalizedError {

    /// Это не ключ активации: не тот состав или не та длина.
    ///
    /// Отличается от `keyDidNotOpen` намеренно: здесь человек ошибся при вводе
    /// и может исправиться сам, а там ключ вводом уже не спасти.
    case malformedKey

    /// Ключ не подошёл или пакет уже забрали.
    ///
    /// **Неверный ключ и испорченный пакет неотличимы по ответу, и это
    /// решение, а не небрежность.** То же, что у кода восстановления в
    /// `AdminAccess`: подбирающему незачем знать, ошибся он ключом или наткнулся
    /// на битый файл.
    case keyDidNotOpen

    /// Пакет собран более новой версией панели.
    ///
    /// Отдельным случаем, потому что иначе разбор уйдёт не туда: человек будет
    /// искать опечатку в ключе, которого не набирал, вместо того чтобы обновить
    /// приложение.
    case packageTooNew

    /// Файл предустановок не прошёл проверку подписи.
    case signatureDidNotMatch

    /// Файл предустановок собран более новой версией.
    case bundleTooNew

    /// Файл предустановок не разобрался.
    case malformedBundle

    public var errorDescription: String? {
        switch self {
        case .malformedKey:
            return NSLocalizedString(
                "Это не похоже на ключ: в нём должно быть двенадцать знаков.",
                comment: "отказ при вводе ключа активации"
            )
        case .keyDidNotOpen:
            return NSLocalizedString(
                "Ключ не подошёл или уже использован. Попросите новый.",
                comment: "отказ при распечатывании пакета активации"
            )
        case .packageTooNew:
            return NSLocalizedString(
                "Пакет собран более новой версией программы — обновитесь.",
                comment: "отказ при распечатывании пакета активации"
            )
        case .signatureDidNotMatch:
            return NSLocalizedString(
                "Подпись файла настроек не сошлась — файл отброшен.",
                comment: "отказ при проверке файла предустановок"
            )
        case .bundleTooNew:
            return NSLocalizedString(
                "Файл настроек собран более новой версией программы.",
                comment: "отказ при проверке файла предустановок"
            )
        case .malformedBundle:
            return NSLocalizedString(
                "Файл настроек не разобрался.",
                comment: "отказ при проверке файла предустановок"
            )
        }
    }
}

import Foundation

/// Код восстановления — то, что вводят вслепую, когда пароль забыт.
///
/// Он не сбрасывает пароль, а расшифровывает его: пароль на рабочем месте
/// базово тот же, что в файле конфигурации, и «сбросить» его локально значило бы
/// развести машину с системой до следующей синхронизации.
///
/// **Честно про стойкость.** Шесть цифр — это миллион вариантов, и от
/// целенаправленного перебора файла настроек они не спасают: PBKDF2 делает
/// перебор дорогим, но не невозможным. Сегодня это и не важно — код зашит в
/// сборку, то есть публичен для всякого, кто откроет бинарник строками. Смысл
/// нынешнего кода в другом: закрыть настройки от менеджера, у которого нет ни
/// кода, ни повода его искать. Настоящей защитой это станет в M8, когда код
/// начнёт приезжать файлом конфигурации — своим у каждой машины.
public enum RecoveryCode {

    /// Сколько цифр в коде. Шесть — согласовано: столько клеток в окне ввода.
    public static let length = 6

    /// Код, зашитый в сборку.
    ///
    /// Временная мера до файла конфигурации (M8) — там он станет своим у
    /// каждого рабочего места. Держится отдельной константой именно затем,
    /// чтобы замена была одной строкой, а не поиском по коду.
    public static let provisioned = "060397"

    /// Приводит введённое к каноническому виду: только цифры.
    ///
    /// Окно ввода само по себе пропускает лишь цифры, но код может прийти и
    /// из файла конфигурации — с пробелом или дефисом посередине.
    public static func normalized(_ input: String) -> String {
        input.filter(\.isNumber)
    }

    /// Годится ли строка как код.
    public static func isWellFormed(_ input: String) -> Bool {
        normalized(input).count == length
    }
}

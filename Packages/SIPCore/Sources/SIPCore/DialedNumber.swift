import Foundation

/// Приведение набранного номера к тому, что можно положить в Request-URI.
///
/// Номер редко набирают руками — его копируют из CRM, а там он записан для
/// человека: `+7 (918) 000-11-22`. Скобки и пробелы в user-part ломают разбор
/// SIP, поэтому раньше такой номер либо уходил на сервер как есть и не
/// дозванивался, либо возвращал оператору отказ «недопустимые символы» — то
/// есть наказывал его за формат чужого источника.
///
/// Живёт в `SIPCore`, а не во вьюхе, по двум причинам. Во-первых, это правило
/// про протокол, а не про оформление: что допустимо в user-part, решает RFC
/// 3261, а не панель. Во-вторых, здесь его видно тестам.
public enum DialedNumber {

    /// Символы, которые остаются.
    ///
    /// Цифры — очевидно. `*` и `#` — потому что это обычные добавочные и коды
    /// сервисов АТС (`*97`), а не украшение. `+` — потому что международный
    /// формат отличается от местного только им, и потерять его значит позвонить
    /// не туда.
    ///
    /// Всё остальное вырезается молча: скобки, дефисы, точки, обычные и
    /// неразрывные пробелы, невидимые отметки направления письма — их щедро
    /// подкладывают веб-страницы, из которых номер и копируют.
    private static let kept = Set("0123456789*#")

    /// Приводит номер к виду, в котором он уйдёт на сервер.
    ///
    /// Правило одно: показывать в поле ровно то, что уйдёт в INVITE. Иначе
    /// оператор видит один номер, а звонок идёт на другой, и разбираться с этим
    /// приходится по журналу.
    public static func normalized(_ raw: String) -> String {
        var digits = ""
        // Плюс имеет смысл только в начале: `8+123` — это не международный
        // номер, а опечатка, и сохранять в ней плюс значит сохранять опечатку.
        var plus = ""

        for character in raw {
            if character == "+" {
                if digits.isEmpty && plus.isEmpty { plus = "+" }
                continue
            }
            if kept.contains(character) { digits.append(character) }
        }

        return plus + digits
    }

    /// Годится ли номер для звонка.
    ///
    /// Пустой не годится, и одного `+` тоже мало: он не номер, а признак
    /// формата.
    public static func isDialable(_ raw: String) -> Bool {
        !normalized(raw).drop(while: { $0 == "+" }).isEmpty
    }
}

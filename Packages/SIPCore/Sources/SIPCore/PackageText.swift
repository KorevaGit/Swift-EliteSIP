import Foundation

/// Строки пакета для тех, кто их сравнивает.
///
/// Нужно тестам. С этапа 8 причина отказа и причина окончания звонка
/// переводятся, а какой язык выберет система на машине, где запускают
/// `swift test`, заранее неизвестно. Проверка вида `reason == "занято"`
/// начинает падать от языка машины, ничего не сообщая о самом коде, — а
/// проверяют такие тесты не перевод, а выбор ветки: что 486 даёт «занято», а
/// не «отказ 486».
///
/// Поэтому ожидание выражается тем же переводом, который берёт код. Там, где
/// у ветки есть своё имя в API — `SIPCallError.emptyTarget.description`,
/// `describeCallFailure(status:reason:)`, — пользоваться надо им, а этим
/// доступом только там, где строка родилась внутри `SIPUserAgent` и имени у
/// неё нет.
enum PackageText {

    static func localized(_ key: String) -> String {
        NSLocalizedString(key, bundle: .module, comment: "")
    }
}

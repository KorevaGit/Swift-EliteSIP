import Compat

/// Следит за тем, доходит ли до нас опрос сервера.
///
/// **Зачем.** Регистрация и достижимость — разные вещи, и расходятся они молча.
/// Клиент показывает «На линии», срок регистрации свежий, а INVITE из очереди
/// раздачи до рабочего места не доходит: обратной дороги через NAT уже нет.
/// Asterisk это видит — его `qualify` не получает ответа, и пир уходит в
/// UNREACHABLE, — а клиент не видит ничего.
///
/// Случай не выдуманный. Архив 18 августа 2026: OPTIONS приходили ровно раз в
/// 60 секунд, потом пропадали на 150, 90, 210 и 270 секунд, и каждый провал
/// кончался в ту же миллисекунду, когда уходил очередной REGISTER. То есть
/// дорога закрывалась и открывалась обратно любым нашим исходящим пакетом, а
/// оператор всё это время считался доступным и лидов не получал.
///
/// **Почему именно опрос.** Это единственный признак обратной дороги, который у
/// клиента есть. Свои пакеты доходят всегда — они открывают дорогу сами; ответы
/// на них приходят по горячей привязке. Чужой запрос, пришедший по своей воле, —
/// первое, что пропадает, и последнее, что возвращается.
///
/// Тип синхронный и без часов внутри: момент приходит аргументом, поэтому
/// проверяется тестом целиком, как и `InboundStreamWatch`.
public struct QualifyWatch: Sendable {

    /// Во сколько раз молчание должно превысить привычный интервал опроса.
    ///
    /// Три: один потерянный OPTIONS — это потерянный пакет, а не потерянная
    /// дорога, и дёргать регистрацию из-за него значит менять редкую беду на
    /// частую. Три подряд на UDP в локальной сети случайностью уже не бывают.
    public static let silenceFactor = 3

    /// Ниже этого выученный интервал не опускается.
    ///
    /// Сразу после REGISTER Asterisk опрашивает пир внеочередно, и такая пара
    /// даёт промежуток в секунды. Без нижней границы он стал бы «привычным
    /// интервалом», а сторож — источником ложных перерегистраций.
    public static let minimumInterval: Interval = .seconds(30)

    /// Когда до нас последний раз дошло хоть что-то со стороны сервера.
    private var lastHeard: MonotonicClock.Instant?

    /// Привычный интервал опроса. `nil` — опросов было меньше двух, и судить
    /// не по чему.
    private var interval: Interval?

    public init() {}

    /// Выученный интервал опроса. Наружу — только ради журнала.
    public var learnedInterval: Interval? { interval }

    /// Пришёл опрос сервера.
    ///
    /// Интервал берётся минимальный из виденных, а не последний: потери делают
    /// промежутки длиннее, и «последний» после первого же провала задрал бы
    /// порог до бесконечности — сторож ослеп бы ровно тогда, когда нужен.
    public mutating func noteQualify(at now: MonotonicClock.Instant) {
        defer { lastHeard = now }
        guard let previous = lastHeard else { return }

        let gap = now - previous
        guard gap > .zero else { return }
        let candidate = max(gap, Self.minimumInterval)
        interval = interval.map { min($0, candidate) } ?? candidate
    }

    /// Дорога заведомо открыта — прошёл наш запрос и вернулся ответ.
    ///
    /// Не учит интервал: промежуток от чужого опроса до нашей регистрации к
    /// частоте опроса отношения не имеет.
    public mutating func noteReachable(at now: MonotonicClock.Instant) {
        lastHeard = now
    }

    /// Потеряна ли обратная дорога.
    ///
    /// Возвращает срок молчания, если пора действовать, и `nil`, если ещё рано
    /// или судить не по чему. Сам факт срабатывания сдвигает отсчёт: следующий
    /// раз наступит не раньше, чем через столько же, — иначе на сервере, до
    /// которого не достучаться вовсе, мы бы перерегистрировались в цикле.
    public mutating func silenceIfLost(at now: MonotonicClock.Instant) -> Interval? {
        guard let interval, let lastHeard else { return nil }
        let silence = now - lastHeard
        guard silence >= interval * Self.silenceFactor else { return nil }
        self.lastHeard = now
        return silence
    }
}
